/**
 * CmxBarcode - a CODE128 or QR code drawn as inline SVG (HFC P4, T4.3).
 *
 * The SVG comes from bwip-js (lib/utils/barcode), which builds it from the value's bars or modules only,
 * so injecting it is safe: no part of the value is copied into the markup as text.
 * Pure: no hooks or context, so it renders inside the print iframe and on the server.
 * A value that cannot be encoded shows the plain code instead of breaking the label.
 */
import * as React from 'react'
import { renderCode128Svg } from '@/lib/utils/barcode/code128'
import { renderQrSvg } from '@/lib/utils/barcode/qr'

export interface CmxBarcodeProps {
  value: string
  kind: 'code128' | 'qr'
  /** Accessible name, e.g. "Order barcode ORD-260101-0001". */
  label: string
  /** CODE128: narrowest bar in px (default 2). */
  moduleWidth?: number
  /** CODE128: bar height in px (default 48). */
  height?: number
  /** QR: width and height in px (default 96). */
  size?: number
  className?: string
}

export function CmxBarcode({ value, kind, label, moduleWidth, height, size, className }: CmxBarcodeProps) {
  let svg: string | null = null
  try {
    svg = kind === 'qr' ? renderQrSvg(value, { size }) : renderCode128Svg(value, { moduleWidth, height })
  } catch {
    svg = null
  }
  if (!svg) {
    return (
      <span className={className} data-barcode-fallback="true">
        <bdi dir="ltr">{value}</bdi>
      </span>
    )
  }
  return (
    <span
      role="img"
      aria-label={label}
      className={className}
      data-barcode={kind}
      // Trusted: generated by bwip-js from bar/module geometry, never from markup in the value.
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  )
}
