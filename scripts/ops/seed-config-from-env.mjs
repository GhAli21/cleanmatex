#!/usr/bin/env node
/**
 * Seeds the Config Registry (sys_ops_config_cf) with the values found in .env files.
 *
 * WHY A SCRIPT AND NOT A MIGRATION: migrations run on every database and are committed to git;
 * environment values differ per database and many are secrets. This script runs on your machine,
 * reads the env files YOU name, and writes a SQL file into a git-ignored folder that you then run
 * (SQL editor) against ONE database. It never connects to a database and never prints a value.
 *
 * Usage (from the repo root):
 *   node scripts/ops/seed-config-from-env.mjs \
 *     --env TENANT_WEB=web-admin/.env.dbcloudjh \
 *     --env HQ_API=../cleanmatexsaas/platform-api/.env.apiclouddbjh \
 *     --env HQ_WEB=../cleanmatexsaas/platform-web/.env.webclouddbjh \
 *     --out supabase/seeds/local/ops_config_values.cloud.sql
 *   Options: --dry-run (names and counts only, writes nothing)
 *            --include-secrets (also store secret values as PLAIN TEXT in db_value; default: off)
 *            --no-store k1,k2 (config keys whose VALUE must not be stored; presence is still recorded)
 *
 * What it writes per key (only keys found in at least one file, or all keys when --all-scopes):
 *   - env_var_scope_val: is_it_there yes/no per scope you supplied (unknown otherwise); `value` only
 *     for NON-secret keys; a 12-hex fingerprint for secrets (never the value).
 *   - env_var_value: the first non-secret value found (NULL for secrets).
 *   - db_value (+ fingerprint, change-log row): only for keys whose policy allows a stored value
 *     (not bootstrap / ENV_ONLY), only when empty, and secrets only with --include-secrets.
 * Bootstrap keys (database URL, Supabase keys, JWT secret, ...) are NEVER stored in the database.
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..', '..');
const mapPath = resolve(repoRoot, 'docs/features/Platform_Operations_Console/config_key_env_map.json');

function parseArgs(argv) {
  const args = { env: {}, out: null, dryRun: false, includeSecrets: false, noStore: new Set() };
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    if (a === '--env') {
      const [scope, file] = String(argv[++i] ?? '').split('=');
      if (!scope || !file) throw new Error('--env expects SCOPE=path');
      args.env[scope.toUpperCase()] = file;
    } else if (a === '--out') args.out = argv[++i];
    else if (a === '--dry-run') args.dryRun = true;
    else if (a === '--include-secrets') args.includeSecrets = true;
    else if (a === '--no-store') String(argv[++i] ?? '').split(',').filter(Boolean).forEach((k) => args.noStore.add(k.trim()));
    else throw new Error(`Unknown argument ${a}`);
  }
  if (Object.keys(args.env).length === 0) throw new Error('Pass at least one --env SCOPE=path');
  if (!args.dryRun && !args.out) throw new Error('Pass --out <file> (or --dry-run)');
  return args;
}

/** Minimal dotenv parser: KEY=VALUE, optional quotes, comments, multi-line quoted values. */
function parseEnvFile(path) {
  const text = readFileSync(resolve(repoRoot, path), 'utf8').replace(/\r\n/g, '\n');
  const out = new Map();
  const lines = text.split('\n');
  for (let i = 0; i < lines.length; i += 1) {
    const m = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$/.exec(lines[i]);
    if (!m) continue;
    let value = m[2].trim();
    const quote = value[0] === '"' || value[0] === "'" ? value[0] : null;
    if (quote) {
      let body = value.slice(1);
      while (!body.endsWith(quote) && i + 1 < lines.length) body += `\n${lines[(i += 1)]}`;
      value = body.endsWith(quote) ? body.slice(0, -1) : body;
    } else {
      const hash = value.search(/\s#/);
      if (hash >= 0) value = value.slice(0, hash).trim();
    }
    out.set(m[1], value);
  }
  return out;
}

const sha = (s) => createHash('sha256').update(s.trim(), 'utf8').digest('hex');
const lit = (s) => (s === null || s === undefined ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`);

function main() {
  const args = parseArgs(process.argv.slice(2));
  const keys = JSON.parse(readFileSync(mapPath, 'utf8'));
  const envs = Object.fromEntries(Object.entries(args.env).map(([scope, file]) => [scope, parseEnvFile(file)]));

  const sql = [
    '-- GENERATED by scripts/ops/seed-config-from-env.mjs — contains environment values. DO NOT COMMIT.',
    `-- Scopes supplied: ${Object.keys(envs).join(', ')}. Secrets as plain text: ${args.includeSecrets ? 'YES' : 'no (fingerprints only)'}.`,
    'BEGIN;',
  ];
  let touched = 0, stored = 0, presence = 0, skippedSecret = 0;

  for (const k of keys) {
    let anyFound = false;
    let firstValue = null;
    const scopes = k.scopes.map((s) => {
      const file = envs[s.scope];
      const name = s.env_var_name;
      if (!file || !name) return s; // scope not supplied: leave "unknown"
      const found = file.has(name) && file.get(name).trim() !== '';
      if (found) {
        anyFound = true;
        const value = file.get(name);
        if (!k.secret && firstValue === null) firstValue = value;
        return { ...s, is_it_there: 'yes', value: k.secret ? null : value, fingerprint: k.secret ? sha(value).slice(0, 12) : null };
      }
      return { ...s, is_it_there: 'no', value: null, fingerprint: null };
    });
    const suppliedScopes = k.scopes.some((s) => envs[s.scope]);
    if (!suppliedScopes) continue;
    touched += 1;
    if (anyFound) presence += 1;

    const sets = [`env_var_scope_val = ${lit(JSON.stringify(scopes))}::jsonb`];
    if (!k.secret && firstValue !== null) sets.push(`env_var_value = ${lit(firstValue)}`);

    // Stored value: only where the policy allows one, never for bootstrap keys.
    const canStore = !k.bootstrap && k.policy !== 'ENV_ONLY' && !args.noStore.has(k.key);
    let secretValue = null;
    if (canStore && anyFound) {
      const primary = k.scopes.map((s) => ({ s, file: envs[s.scope] })).find(({ s, file }) => file && s.env_var_name && file.has(s.env_var_name) && file.get(s.env_var_name).trim() !== '');
      const value = primary ? envs[primary.s.scope].get(primary.s.env_var_name).trim() : null;
      if (value !== null) {
        if (k.secret && !args.includeSecrets) skippedSecret += 1;
        else {
          secretValue = value;
          stored += 1;
        }
      }
    }
    sql.push(`UPDATE public.sys_ops_config_cf SET ${sets.join(', ')}, updated_at = now(), updated_info = 'seed-config-from-env' WHERE config_key = ${lit(k.key)};`);
    if (secretValue !== null) {
      const fp = sha(secretValue);
      sql.push(
        `UPDATE public.sys_ops_config_cf SET db_value = ${lit(secretValue)}, db_value_fingerprint = ${lit(fp)}, value_updated_at = now(), value_updated_by = 'seed-config-from-env' ` +
          `WHERE config_key = ${lit(k.key)} AND db_value IS NULL AND db_value_enc IS NULL AND NOT is_encrypted;`,
        `INSERT INTO public.sys_ops_config_chg_log (config_key, action, actor, old_fingerprint, new_fingerprint, created_info) ` +
          `SELECT ${lit(k.key)}, 'SET', 'seed-config-from-env', NULL, ${lit(fp)}, 'seed-config-from-env' ` +
          `WHERE EXISTS (SELECT 1 FROM public.sys_ops_config_cf WHERE config_key = ${lit(k.key)} AND db_value_fingerprint = ${lit(fp)} AND value_updated_by = 'seed-config-from-env');`,
      );
    }
  }
  sql.push('COMMIT;');

  console.log(`keys in map: ${keys.length}; touched (scope supplied): ${touched}; present in a file: ${presence}; values stored: ${stored}; secret values skipped (no --include-secrets): ${skippedSecret}`);
  if (args.dryRun) {
    console.log('dry run: nothing written');
    return;
  }
  const out = resolve(repoRoot, args.out);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, `${sql.join('\n')}\n`, { mode: 0o600 });
  console.log(`written ${args.out} (contains environment values; keep it out of git)`);
}

main();
