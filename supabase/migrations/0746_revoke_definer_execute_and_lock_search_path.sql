-- Migration: 0746_revoke_definer_execute_and_lock_search_path.sql
-- Purpose:   Stop anon and authenticated from executing SECURITY DEFINER
--            functions, then grant authenticated only the reviewed allowlist.
--            Lock search_path on those functions and on every other public
--            function the public key can still execute. Bodies are not rewritten.
--            Extension functions (pg_trgm) are left to the extension.
-- Affected:  public functions owned by the migration role, default execute
--            privileges of postgres, and supabase_admin when permitted
-- Plan:      docs/pending_to_production/16_11_2026/S0_privilege_lockdown_PLAN.md
--            Phase C. Allowlist: S0_authenticated_allowlist.md
--            Do not edit this file after it is applied.
-- =============================================================================

BEGIN;

SET LOCAL lock_timeout = '3s';

-- Owner executes its own functions, so a definer wrapper can still call cmx_can
-- after authenticated loses that grant. service_role is granted explicitly
-- because BYPASSRLS does not bypass a missing EXECUTE grant.
DO $revoke_definers$
DECLARE
  fn regprocedure;
BEGIN
  FOR fn IN
    SELECT p.oid::regprocedure
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'public'
      AND p.prosecdef
      AND NOT EXISTS (
        SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e'
      )
  LOOP
    EXECUTE format('REVOKE ALL ON FUNCTION %s FROM PUBLIC, anon, authenticated', fn);
    EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO service_role', fn);
  END LOOP;
END
$revoke_definers$;

-- Reviewed user-JWT functions. Each body checks auth.uid(), the JWT session,
-- or the authenticated role plus the tenant. Names are literal on purpose:
-- the migration must not discover extra grants at apply time.
GRANT EXECUTE ON FUNCTION public.fix_order_data(p_tenant_org_id uuid, p_steps text[], p_order_id uuid, p_dry_run boolean) TO authenticated;
GRANT EXECUTE ON FUNCTION public.fn_auth_own_tenants() TO authenticated;
GRANT EXECUTE ON FUNCTION public.fn_auth_session_choose_tenant(p_org_user_id uuid) TO authenticated;
GRANT EXECUTE ON FUNCTION public.fn_auth_session_open_picker(p_remember_me boolean, p_ip_address inet, p_user_agent text, p_device_label text, p_device_id_hash text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.fn_auth_session_validate(p_touch boolean, p_ip_address inet) TO authenticated;
GRANT EXECUTE ON FUNCTION public.fn_label_printing_resolve(p_tenant_id uuid, p_branch_id uuid) TO authenticated;
GRANT EXECUTE ON FUNCTION public.get_user_permissions() TO authenticated;
GRANT EXECUTE ON FUNCTION public.get_user_roles() TO authenticated;
GRANT EXECUTE ON FUNCTION public.get_user_tenants() TO authenticated;
GRANT EXECUTE ON FUNCTION public.has_all_permissions(p_permissions text[]) TO authenticated;
GRANT EXECUTE ON FUNCTION public.has_any_permission(p_permissions text[]) TO authenticated;
GRANT EXECUTE ON FUNCTION public.has_permission(p_permission text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.has_resource_permission(p_permission text, p_resource_type text, p_resource_id uuid) TO authenticated;

-- pg_catalog first, pg_temp last. Extra schemas are added only when the body
-- names them. This blocks a temporary object from shadowing a function the
-- definer would otherwise run as its owner.
DO $search_path$
DECLARE
  fn record;
  fn_path text;
  body text;
BEGIN
  FOR fn IN
    SELECT p.oid::regprocedure AS signature, p.prosrc
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    JOIN pg_roles owner_role ON owner_role.oid = p.proowner
    WHERE n.nspname = 'public'
      AND owner_role.rolname = current_user
      AND NOT EXISTS (
        SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e'
      )
      AND (
        p.prosecdef
        OR has_function_privilege('anon', p.oid, 'EXECUTE')
        OR has_function_privilege('authenticated', p.oid, 'EXECUTE')
      )
  LOOP
    body := lower(coalesce(fn.prosrc, ''));
    fn_path := 'pg_catalog, public';
    IF body ~ '(^|[^a-z0-9_])auth\.' THEN
      fn_path := fn_path || ', auth';
    END IF;
    IF body ~ '(^|[^a-z0-9_])extensions\.' THEN
      fn_path := fn_path || ', extensions';
    END IF;
    IF body ~ '(^|[^a-z0-9_])net\.' THEN
      fn_path := fn_path || ', net';
    END IF;
    IF body ~ '(^|[^a-z0-9_])storage\.' THEN
      fn_path := fn_path || ', storage';
    END IF;
    IF body ~ '(^|[^a-z0-9_])cron\.' THEN
      fn_path := fn_path || ', cron';
    END IF;
    IF body ~ '(^|[^a-z0-9_])vault\.' THEN
      fn_path := fn_path || ', vault';
    END IF;
    fn_path := fn_path || ', pg_temp';
    EXECUTE format('ALTER FUNCTION %s SET search_path = %s', fn.signature, fn_path);
    RAISE NOTICE 's0 search_path % = %', fn.signature, fn_path;
  END LOOP;
END
$search_path$;

-- Future functions created by postgres do not inherit PUBLIC execute.
-- A later migration that wants authenticated to call a function must GRANT it.
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public
  REVOKE ALL ON FUNCTIONS FROM PUBLIC, anon, authenticated;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public
  GRANT ALL ON FUNCTIONS TO service_role;

DO $admin_function_defaults$
BEGIN
  IF pg_has_role(current_user, 'supabase_admin', 'MEMBER') THEN
    EXECUTE 'ALTER DEFAULT PRIVILEGES FOR ROLE supabase_admin IN SCHEMA public REVOKE ALL ON FUNCTIONS FROM PUBLIC, anon, authenticated';
    EXECUTE 'ALTER DEFAULT PRIVILEGES FOR ROLE supabase_admin IN SCHEMA public GRANT ALL ON FUNCTIONS TO service_role';
  ELSE
    RAISE NOTICE 's0: current_user % cannot change supabase_admin function default privileges. Run scripts/db/s0-supabase-admin-default-privileges.sql as supabase_admin.', current_user;
  END IF;
END
$admin_function_defaults$;

DO $check$
DECLARE
  open_count integer;
  unlocked_count integer;
  extra_count integer;
  allowed text[] := ARRAY[
    'fix_order_data(p_tenant_org_id uuid, p_steps text[], p_order_id uuid, p_dry_run boolean)',
    'fn_auth_own_tenants()',
    'fn_auth_session_choose_tenant(p_org_user_id uuid)',
    'fn_auth_session_open_picker(p_remember_me boolean, p_ip_address inet, p_user_agent text, p_device_label text, p_device_id_hash text)',
    'fn_auth_session_validate(p_touch boolean, p_ip_address inet)',
    'fn_label_printing_resolve(p_tenant_id uuid, p_branch_id uuid)',
    'get_user_permissions()',
    'get_user_roles()',
    'get_user_tenants()',
    'has_all_permissions(p_permissions text[])',
    'has_any_permission(p_permissions text[])',
    'has_permission(p_permission text)',
    'has_resource_permission(p_permission text, p_resource_type text, p_resource_id uuid)'
  ];
BEGIN
  SELECT count(*) INTO open_count
  FROM pg_proc p
  JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'public'
    AND p.prosecdef
    AND (
      has_function_privilege('anon', p.oid, 'EXECUTE')
      OR EXISTS (
        SELECT 1
        FROM aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) AS acl_item
        WHERE acl_item.grantee = 0
          AND acl_item.privilege_type = 'EXECUTE'
      )
      OR NOT has_function_privilege('service_role', p.oid, 'EXECUTE')
    );

  IF open_count > 0 THEN
    RAISE EXCEPTION 's0 function lockdown failed: % SECURITY DEFINER functions are still executable by anon or PUBLIC, or lost service_role execute', open_count;
  END IF;

  SELECT count(*) INTO extra_count
  FROM pg_proc p
  JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'public'
    AND p.prosecdef
    AND has_function_privilege('authenticated', p.oid, 'EXECUTE')
    AND (p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')') <> ALL (allowed);

  IF extra_count > 0 THEN
    RAISE EXCEPTION 's0 function lockdown failed: % SECURITY DEFINER functions are executable by authenticated and are not on the allowlist', extra_count;
  END IF;

  SELECT count(*) INTO unlocked_count
  FROM pg_proc p
  JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'public'
    AND p.prosecdef
    AND NOT EXISTS (
      SELECT 1
      FROM unnest(coalesce(p.proconfig, ARRAY[]::text[])) AS cfg
      WHERE cfg LIKE 'search_path=%'
    );

  IF unlocked_count > 0 THEN
    RAISE EXCEPTION 's0 function lockdown failed: % SECURITY DEFINER functions still have no search_path', unlocked_count;
  END IF;
END
$check$;

COMMIT;
