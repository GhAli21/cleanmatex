     OR public.fn_cmx_dt_is_valid_zone('EST') OR public.fn_cmx_dt_is_valid_zone('Etc/GMT-4')
     OR NOT public.fn_cmx_dt_is_valid_zone('UTC') THEN
    RAISE EXCEPTION '0842 verification: D32 catalog rule broken';
  END IF;
  -- c. Q8 for the catalog: active rows with a non-IANA shape (only possible from HQ edits before 0842).
  SELECT count(*) INTO v_n FROM public.sys_timezone_cd
   WHERE is_active IS TRUE AND code <> 'UTC'
     AND (code !~ '^[A-Za-z]+(/[A-Za-z0-9_+-]+)+$' OR code ~ '^(posix|right|SystemV|Etc)/');
  IF v_n > 0 THEN
    RAISE WARNING '0842 verification: % active catalog rows have a non-IANA shape; deactivate them (Q8)', v_n;
  END IF;
