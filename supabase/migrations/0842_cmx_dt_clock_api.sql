LANGUAGE plpgsql
STABLE
SECURITY INVOKER
SET search_path = pg_catalog, public, auth, pg_temp
AS $$
DECLARE
  v_zone TEXT;
BEGIN
  -- Closed codes shared with @cmx/clock (OPERATIONAL_ZONE_OPERATIONS, SQL_DOOR_OPERATIONS) and fn_cmx_dt_operations().
  IF p_operation NOT IN ('accept_order', 'ready_by', 'pos_session', 'delivery', 'invoice', 'ledger', 'notify') THEN
