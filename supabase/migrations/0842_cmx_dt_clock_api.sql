-- ----------------------------------------------------------------------------
-- 4. Catalog integrity trigger (insert or update). Does not call fn_cmx_dt_is_valid_zone (circular).
-- ----------------------------------------------------------------------------
CREATE FUNCTION public.fn_cmx_dt__catalog_integrity()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
  c_utc_family CONSTANT TEXT[] := ARRAY['Etc/UTC', 'Etc/UCT', 'Etc/Universal', 'Etc/Zulu', 'Etc/GMT', 'Etc/GMT0', 'Etc/GMT+0',
                                        'Etc/GMT-0', 'Etc/Greenwich', 'GMT', 'GMT0', 'GMT+0', 'GMT-0', 'Greenwich', 'UCT',
                                        'Universal', 'Zulu'];
BEGIN
  IF NEW.code <> 'UTC' AND NOT (NEW.code = ANY (c_utc_family) AND NOT NEW.is_canonical AND NEW.link_target = 'UTC') THEN
    IF NEW.code !~ '^[A-Za-z]+(/[A-Za-z0-9_+-]+)+$' OR NEW.code ~ '^(posix|right|SystemV|Etc)/' THEN
      RAISE EXCEPTION 'CLOCK_CATALOG_BAD_NAME: % is not an IANA Area/Location name', NEW.code
        USING ERRCODE = '22023', HINT = 'No abbreviations, offsets, Etc/GMT+-N, posix/ or right/ names (D16, D32).';
    END IF;
  END IF;
  IF NEW.is_canonical THEN
    IF NEW.link_target IS NOT NULL OR NEW.iana_name IS DISTINCT FROM NEW.code THEN
      RAISE EXCEPTION 'CLOCK_CATALOG_BAD_LINK: canonical % must have no link and iana_name = code', NEW.code USING ERRCODE = '23514';
    END IF;
  ELSE
    IF NEW.link_target IS NULL OR NEW.iana_name IS DISTINCT FROM NEW.link_target
       OR NOT EXISTS (SELECT 1 FROM public.sys_timezone_cd t WHERE t.code = NEW.link_target AND t.is_canonical) THEN
      RAISE EXCEPTION 'CLOCK_CATALOG_BAD_LINK: alias % must point at a canonical row', NEW.code USING ERRCODE = '23514';
    END IF;
    IF NEW.is_active IS TRUE THEN
      RAISE EXCEPTION 'CLOCK_CATALOG_BAD_LINK: alias % cannot be active (it is never offered in the picker)', NEW.code USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.is_canonical
       AND EXISTS (SELECT 1 FROM public.sys_timezone_cd a WHERE a.link_target = OLD.code) THEN
      RAISE EXCEPTION 'CLOCK_CATALOG_BAD_LINK: % has aliases; it cannot become an alias', OLD.code USING ERRCODE = '23514';
    END IF;
  END IF;
  RETURN NEW;
END $$;
COMMENT ON FUNCTION public.fn_cmx_dt__catalog_integrity() IS
  'BEFORE INSERT/UPDATE trigger on sys_timezone_cd (0842, D28/D32): IANA name shape (Area/Location or UTC; the UTC-family names only as aliases of UTC); no abbreviations, offsets, Etc/GMT+-N, posix/ or right/; a canonical row has no link and iana_name = code; an alias points at a canonical row, has iana_name = link_target and is never active; a canonical row with aliases cannot become an alias. Does not call fn_cmx_dt_is_valid_zone.';
REVOKE ALL ON FUNCTION public.fn_cmx_dt__catalog_integrity() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS trg_sys_timezone_cd_integrity ON public.sys_timezone_cd;
CREATE TRIGGER trg_sys_timezone_cd_integrity
  BEFORE INSERT OR UPDATE ON public.sys_timezone_cd
  FOR EACH ROW EXECUTE FUNCTION public.fn_cmx_dt__catalog_integrity();
COMMENT ON TRIGGER trg_sys_timezone_cd_integrity ON public.sys_timezone_cd IS 'Zone catalog integrity (D28, D32).';


