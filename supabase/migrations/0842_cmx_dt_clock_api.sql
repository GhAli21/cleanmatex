-- Gate for the test override. Returns NULL (real time) unless BOTH gates pass, in this order:
--   1. session_user AND current_user are postgres or a superuser. PostgREST sessions run as
--      authenticator, and SET ROLE authenticated / anon / service_role changes current_user, so app
--      traffic stops here before the owner-only table is read (review row 18, T66);
--   2. cmx_dt_env_cf.env = 'test'.
-- The setting must carry an explicit offset (Z or +hh:mm). Any refusal emits WARNING CMX_FAKE_NOW_IGNORED.
CREATE FUNCTION public.fn_cmx_dt__fake_instant()
RETURNS TIMESTAMPTZ
LANGUAGE plpgsql
STABLE
PARALLEL SAFE
SECURITY INVOKER
SET search_path = pg_catalog, public, pg_temp
AS $fn$
DECLARE
  v_raw TEXT := pg_catalog.current_setting('cmx.fake_now', true);
  v_env TEXT;
  v_at  TIMESTAMPTZ;
BEGIN
  IF coalesce(v_raw, '') = '' THEN
    RETURN NULL;
  END IF;
  IF NOT (session_user = 'postgres' OR EXISTS (SELECT 1 FROM pg_catalog.pg_roles r WHERE r.rolname = session_user AND r.rolsuper))
     OR NOT (current_user = 'postgres' OR EXISTS (SELECT 1 FROM pg_catalog.pg_roles r WHERE r.rolname = current_user AND r.rolsuper)) THEN
    RAISE WARNING 'CMX_FAKE_NOW_IGNORED'
      USING DETAIL = format('session user %s / current user %s may not use the test clock', session_user, current_user);
    RETURN NULL;
  END IF;
  SELECT e.env INTO v_env FROM public.cmx_dt_env_cf e WHERE e.config_id;
  IF v_env IS DISTINCT FROM 'test' THEN
    RAISE WARNING 'CMX_FAKE_NOW_IGNORED' USING DETAIL = 'cmx_dt_env_cf.env is not the test value';
    RETURN NULL;
  END IF;
  IF v_raw !~ '(Z|z|[+-][0-9]{2}(:?[0-9]{2})?)$' THEN
    RAISE WARNING 'CMX_FAKE_NOW_IGNORED' USING DETAIL = 'cmx.fake_now needs an explicit offset (Z or +hh:mm)';
    RETURN NULL;
  END IF;
  BEGIN
    v_at := v_raw::TIMESTAMPTZ;
  EXCEPTION WHEN OTHERS THEN
    RAISE WARNING 'CMX_FAKE_NOW_IGNORED' USING DETAIL = format('cmx.fake_now is not an instant: %s', v_raw);
    RETURN NULL;
  END;
  RETURN v_at;
END
$fn$;
COMMENT ON FUNCTION public.fn_cmx_dt__fake_instant() IS
  'Internal test-clock gate (MASTER_PLAN_v2 §5.0). No arguments. Returns the cmx.fake_now instant only when session_user and current_user are postgres/superuser AND the cmx_dt_env_cf row is in test mode; otherwise NULL plus WARNING CMX_FAKE_NOW_IGNORED. Production never passes the gate.';

CREATE FUNCTION public.fn_cmx_dt__fake_now()
RETURNS TIMESTAMPTZ
LANGUAGE sql
STABLE
PARALLEL SAFE
SECURITY INVOKER
SET search_path = pg_catalog, public, pg_temp
AS $fn$
  SELECT coalesce(public.fn_cmx_dt__fake_instant(), pg_catalog.now())
$fn$;
COMMENT ON FUNCTION public.fn_cmx_dt__fake_now() IS
  'Internal slow path of fn_cmx_dt_now(), reached only when cmx.fake_now is set. No arguments. Returns the gated fake instant, else the built-in transaction time.';

CREATE FUNCTION public.fn_cmx_dt__fake_clock()
RETURNS TIMESTAMPTZ
LANGUAGE plpgsql
VOLATILE
PARALLEL SAFE
SECURITY INVOKER
SET search_path = pg_catalog, public, pg_temp
AS $fn$
DECLARE
  v_fake TIMESTAMPTZ := public.fn_cmx_dt__fake_instant();
BEGIN
  IF v_fake IS NULL THEN
    RETURN pg_catalog.clock_timestamp();
  END IF;
  -- The fake clock still moves: fake instant + real time elapsed since the transaction started.
  RETURN v_fake + (pg_catalog.clock_timestamp() - pg_catalog.now());
END
$fn$;
COMMENT ON FUNCTION public.fn_cmx_dt__fake_clock() IS
  'Internal slow path of fn_cmx_dt_clock(), reached only when cmx.fake_now is set. No arguments. Returns fake instant + real elapsed time when the gate passes, else the built-in wall clock.';

-- Fast path: LANGUAGE sql, STABLE, no SET clause, so the planner inlines it and production pays
-- one current_setting() call. Every name is schema-qualified (no search_path needed).
CREATE FUNCTION public.fn_cmx_dt_now()
RETURNS TIMESTAMPTZ
LANGUAGE sql
STABLE
PARALLEL SAFE
AS $fn$
  SELECT CASE WHEN coalesce(pg_catalog.current_setting('cmx.fake_now', true), '') = ''
              THEN pg_catalog.now()
              ELSE public.fn_cmx_dt__fake_now()
         END
$fn$;
COMMENT ON FUNCTION public.fn_cmx_dt_now() IS
  'Our transaction clock (D25): equals the built-in transaction time in production (the same instant for every row of one action). Honors the test-only setting cmx.fake_now when the §5.0 gate passes. No arguments. Use it for every new default, trigger and function from 0842 on. TS mirror dtNow(clock).';

CREATE FUNCTION public.fn_cmx_dt_clock()
RETURNS TIMESTAMPTZ
LANGUAGE sql
