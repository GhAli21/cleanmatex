-- Stored zones before any change (tenant, branch, HQ), for the no-demotion proof in section 6.
CREATE TEMP TABLE zz_tz_stored ON COMMIT DROP AS
SELECT s.kind, s.zone, z.is_active AS was_active
  FROM (SELECT DISTINCT 'tenant'::TEXT AS kind, t.timezone::TEXT AS zone FROM public.org_tenants_mst t WHERE t.timezone IS NOT NULL
        UNION SELECT DISTINCT 'branch', b.timezone_code::TEXT FROM public.org_branches_mst b WHERE b.timezone_code IS NOT NULL
        UNION SELECT 'hq', h.timezone::TEXT FROM public.hq_general_config h WHERE h.timezone IS NOT NULL) s
  LEFT JOIN public.sys_timezone_cd z ON z.code = s.zone;

-- Preflight: a stored code must never become an alias (D32, §7.1.1). Fails the migration with the list.
DO $$
DECLARE v_bad TEXT;
BEGIN
  SELECT string_agg(format('%s %s -> alias of %s', s.kind, s.zone, sd.link_target), '; ' ORDER BY s.zone)
    INTO v_bad
    FROM zz_tz_stored s JOIN zz_tz_seed sd ON sd.code = s.zone AND NOT sd.is_canonical;
  IF v_bad IS NOT NULL THEN
    RAISE EXCEPTION 'CLOCK_CATALOG_DEMOTION_BLOCKED: stored zones would become aliases: %', v_bad
      USING ERRCODE = 'P0001', HINT = 'Save the canonical name on those rows first (Q15), then apply 0842 again.';
  END IF;
END $$;

