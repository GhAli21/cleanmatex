CREATE FUNCTION public.fn_cmx_dt_instant_at_zone(p_zone TEXT, p_date DATE, p_time TIME, p_disambiguation TEXT DEFAULT 'reject')
RETURNS TIMESTAMPTZ
LANGUAGE plpgsql
STABLE
PARALLEL SAFE
SECURITY INVOKER
SET search_path = pg_catalog, public, pg_temp
AS $fn$
DECLARE
  v_local TIMESTAMP;  -- CIVIL: the wall date-time asked for
  v_guess TIMESTAMPTZ;
  v_off_a INTERVAL;
  v_off_b INTERVAL;
  v_a     TIMESTAMPTZ;
  v_b     TIMESTAMPTZ;
  v_a_ok  BOOLEAN;
  v_b_ok  BOOLEAN;
BEGIN
  IF p_disambiguation IS NULL OR p_disambiguation NOT IN ('compatible', 'earlier', 'later', 'reject') THEN
    RAISE EXCEPTION 'CLOCK_SETTING_INVALID: disambiguation %', coalesce(p_disambiguation, '<null>') USING ERRCODE = '22023';
  END IF;
  IF coalesce(p_zone, '') = '' THEN
    RAISE EXCEPTION 'TIMEZONE_NOT_CONFIGURED' USING ERRCODE = 'P0001', DETAIL = 'explicit zone is empty';
  END IF;
  IF p_date IS NULL THEN
    RAISE EXCEPTION 'INVALID_CIVIL_DATE: date is required' USING ERRCODE = '22007';
  END IF;
  IF p_time IS NULL THEN
    RAISE EXCEPTION 'INVALID_LOCAL_TIME: time is required' USING ERRCODE = '22007';
  END IF;
  v_local := p_date + p_time;
  v_guess := v_local AT TIME ZONE 'UTC';
  -- Offsets one day before and after: at most one transition sits between them in real tzdb data.
  v_off_a := ((v_guess - INTERVAL '1 day') AT TIME ZONE p_zone) - ((v_guess - INTERVAL '1 day') AT TIME ZONE 'UTC');
  v_off_b := ((v_guess + INTERVAL '1 day') AT TIME ZONE p_zone) - ((v_guess + INTERVAL '1 day') AT TIME ZONE 'UTC');
  v_a := v_guess - v_off_a;
  v_b := v_guess - v_off_b;
  v_a_ok := (v_a AT TIME ZONE p_zone) = v_local;
  v_b_ok := (v_b AT TIME ZONE p_zone) = v_local;
  IF v_a_ok AND v_b_ok AND v_a <> v_b THEN
    -- Overlap: the wall time happens twice.
    IF p_disambiguation = 'reject' THEN
      RAISE EXCEPTION 'LOCAL_TIME_AMBIGUOUS' USING ERRCODE = 'P0001',
        DETAIL = format('%s %s happens twice in %s', p_date, p_time, p_zone), HINT = 'Choose earlier or later.';
    END IF;
    RETURN CASE WHEN p_disambiguation = 'later' THEN greatest(v_a, v_b) ELSE least(v_a, v_b) END;
  ELSIF v_a_ok OR v_b_ok THEN
    RETURN CASE WHEN v_a_ok THEN v_a ELSE v_b END;
  END IF;
  -- Gap: the wall time does not exist. compatible / later move forward by the gap, earlier moves back.
  IF p_disambiguation = 'reject' THEN
    RAISE EXCEPTION 'LOCAL_TIME_NONEXISTENT' USING ERRCODE = 'P0001',
      DETAIL = format('%s %s does not exist in %s (clock change)', p_date, p_time, p_zone);
  END IF;
  RETURN CASE WHEN p_disambiguation = 'earlier' THEN v_guess - v_off_b ELSE v_guess - v_off_a END;
END
$fn$;
COMMENT ON FUNCTION public.fn_cmx_dt_instant_at_zone(TEXT, DATE, TIME, TEXT) IS
  'Local date p_date + time p_time in the explicit zone p_zone to an instant. p_disambiguation: compatible (gap -> later, overlap -> earlier), earlier, later, reject (default, for typed input: raises LOCAL_TIME_NONEXISTENT in a DST gap and LOCAL_TIME_AMBIGUOUS in an overlap). Same answers as Temporal (shared vectors). TS mirror dtInstantAtZone.';

