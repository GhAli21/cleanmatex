    FROM zz_tz_stored s
    JOIN public.sys_timezone_cd z ON z.code = s.zone
   WHERE NOT z.is_canonical OR (s.was_active IS TRUE AND z.is_active IS NOT TRUE);
  IF v_bad IS NOT NULL THEN
    RAISE EXCEPTION '0842 verification: stored zones demoted or deactivated: %', v_bad;
  END IF;
  -- b. D32: Asia/Muscat and the other country zones stay canonical; aliases normalize; abbreviations stay invalid.
  IF EXISTS (SELECT 1 FROM public.sys_timezone_cd WHERE code IN ('Asia/Muscat', 'Asia/Kuwait', 'Asia/Bahrain', 'Asia/Aden', 'UTC') AND NOT is_canonical)
     OR public.fn_cmx_dt_canonical_zone('Asia/Calcutta') IS DISTINCT FROM 'Asia/Kolkata'
