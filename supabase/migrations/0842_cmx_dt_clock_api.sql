  SELECT count(*) INTO v_n FROM public.fn_cmx_dt_chk_catalog_unknown(NULL);
  IF v_n > 0 THEN
    RAISE WARNING '0842 verification: % active catalog zones are unknown to this Postgres (Q4)', v_n;
  END IF;
  -- e. notify resolves like every other code at organization level (Q6 sample).
  IF EXISTS (SELECT 1 FROM public.org_tenants_mst t
              WHERE public.fn_cmx_dt_zone(t.id, 'notify', NULL) IS DISTINCT FROM public.fn_cmx_dt_zone(t.id, 'accept_order', NULL)) THEN
    RAISE EXCEPTION '0842 verification: notify does not resolve like accept_order at organization level';
  END IF;
  -- f. Setup health: every CLOCK check runs for every active tenant without ERROR (0709 rule).
  SELECT count(*) FILTER (WHERE r.status = 'ERROR'), count(*) INTO v_err, v_n
    FROM public.org_tenants_mst t
