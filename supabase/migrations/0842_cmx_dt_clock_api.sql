              THEN pg_catalog.clock_timestamp()
              ELSE public.fn_cmx_dt__fake_clock()
         END
$fn$;
COMMENT ON FUNCTION public.fn_cmx_dt_clock() IS
  'Our moving clock (D25): equals the built-in moving wall clock in production. Only for elapsed-time measurement and long loops; stamps use fn_cmx_dt_now(). Honors cmx.fake_now under the §5.0 gate (fake instant + real elapsed time). No arguments. TS mirror dtClock(clock).';

