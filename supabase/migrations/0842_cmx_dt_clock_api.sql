CREATE FUNCTION public.fn_cmx_dt_health(p_tenant UUID DEFAULT NULL)
RETURNS TABLE (check_code TEXT, severity TEXT, tenant_org_id UUID, branch_id UUID, detail JSONB)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $fn$
DECLARE
  f RECORD;
BEGIN
  PERFORM public.fn_cmx_dt__guard_scope(p_tenant);
  -- Discovers every fn_cmx_dt_chk_*(uuid) so later migrations add checks without replacing this body.
  FOR f IN
    SELECT p.proname
      FROM pg_catalog.pg_proc p
      JOIN pg_catalog.pg_namespace n ON n.oid = p.pronamespace
     WHERE n.nspname = 'public' AND p.proname LIKE 'fn\_cmx\_dt\_chk\_%'
       AND p.pronargs = 1 AND p.proargtypes[0] = 'uuid'::regtype
     ORDER BY p.proname
  LOOP
    BEGIN
      RETURN QUERY EXECUTE format('SELECT c.check_code, c.severity, c.tenant_org_id, c.branch_id, c.detail FROM public.%I($1) c', f.proname)
        USING p_tenant;
    EXCEPTION WHEN OTHERS THEN
      -- One broken check must not hide the others.
      check_code := upper(replace(f.proname, 'fn_cmx_dt_chk_', 'CLOCK_'));
      severity := 'error';
      tenant_org_id := p_tenant;
      branch_id := NULL;
      detail := jsonb_build_object('status', 'ERROR', 'sqlstate', SQLSTATE, 'message', SQLERRM);
      RETURN NEXT;
    END;
  END LOOP;
END
