  IF p_date IS NULL OR p_n IS NULL THEN
    RETURN NULL;
  END IF;
  -- Interval month / year arithmetic on a date clamps to the month end (31 Jan + 1 month = 28/29 Feb).
  IF p_unit = 'DAY' THEN
    RETURN p_date + p_n;
  ELSIF p_unit = 'MONTH' THEN
    RETURN (p_date + make_interval(months => p_n))::DATE;
  END IF;
  RETURN (p_date + make_interval(years => p_n))::DATE;
END
$fn$;
COMMENT ON FUNCTION public.fn_cmx_dt_civil_add(DATE, INTEGER, TEXT) IS
  'Civil date arithmetic: p_date plus p_n units of p_unit (DAY, MONTH with end-of-month clamp, YEAR with 29 Feb -> 28 Feb). No zone involved. Unknown unit raises CLOCK_SETTING_INVALID; NULL date or count -> NULL. TS mirror dtCivilAdd.';

CREATE FUNCTION public.fn_cmx_dt_period_key_in(p_zone TEXT, p_grain TEXT, p_at TIMESTAMPTZ,
                                               p_week_start SMALLINT DEFAULT NULL, p_fy_start SMALLINT DEFAULT NULL)
RETURNS TEXT
LANGUAGE plpgsql
STABLE
PARALLEL SAFE
SECURITY INVOKER
SET search_path = pg_catalog, public, pg_temp
AS $fn$
DECLARE
  v_d    DATE;
  v_back INTEGER;
BEGIN
  IF p_grain IS NULL OR p_grain NOT IN ('DAY', 'WEEK', 'MONTH', 'YEAR', 'FY') THEN
    RAISE EXCEPTION 'CLOCK_SETTING_INVALID: grain %', coalesce(p_grain, '<null>') USING ERRCODE = '22023';
  END IF;
  v_d := public.fn_cmx_dt_today_in(p_zone, p_at);
  IF p_grain = 'DAY' THEN
    RETURN to_char(v_d, 'YYYYMMDD');
  ELSIF p_grain = 'MONTH' THEN
    RETURN to_char(v_d, 'YYYYMM');
  ELSIF p_grain = 'YEAR' THEN
    RETURN to_char(v_d, 'YYYY');
  ELSIF p_grain = 'WEEK' THEN
    IF p_week_start IS NULL OR p_week_start NOT BETWEEN 1 AND 7 THEN
      RAISE EXCEPTION 'CLOCK_SETTING_INVALID: week start %', coalesce(p_week_start::TEXT, '<null>')
        USING ERRCODE = '22023', HINT = 'ISO weekday 1 (Monday) .. 7 (Sunday).';
    END IF;
    v_back := (extract(isodow FROM v_d)::INTEGER - p_week_start + 7) % 7;
    RETURN 'W' || to_char(v_d - v_back, 'YYYYMMDD');
  END IF;
  -- FY: 'FY' + the calendar year in which the fiscal year starts (same rule as fn_doc_seq_period_key, 0670).
  IF p_fy_start IS NULL OR p_fy_start NOT BETWEEN 1 AND 12 THEN
    RAISE EXCEPTION 'CLOCK_SETTING_INVALID: fiscal year start month %', coalesce(p_fy_start::TEXT, '<null>') USING ERRCODE = '22023';
  END IF;
  RETURN 'FY' || lpad((extract(year FROM v_d)::INTEGER
                       - CASE WHEN extract(month FROM v_d)::INTEGER < p_fy_start THEN 1 ELSE 0 END)::TEXT, 4, '0');
END
$fn$;
COMMENT ON FUNCTION public.fn_cmx_dt_period_key_in(TEXT, TEXT, TIMESTAMPTZ, SMALLINT, SMALLINT) IS
  'Period key of instant p_at in the explicit zone p_zone. p_grain: DAY YYYYMMDD, MONTH YYYYMM, YEAR YYYY, WEEK W + civil date of the first day of the week (needs p_week_start, ISO 1..7), FY FY + the year in which the fiscal year starts (needs p_fy_start 1..12; start month 4: 2027-02-10 -> FY2026, same as doc-seq 0670). Missing or bad input raises CLOCK_SETTING_INVALID. TS mirror dtPeriodKey.';

