-- 2. BEFORE INSERT Trigger: Auto-Diff `changed_fields` + Compute `row_hash`
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.fn_hq_audit_before_insert()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_prev_hash TEXT;
  v_canonical TEXT;
  v_diff_keys TEXT[];
BEGIN
  IF NEW.id IS NULL THEN
    NEW.id := gen_random_uuid();
  END IF;

  IF NEW.created_at IS NULL THEN
    NEW.created_at := clock_timestamp();
  END IF;

  IF NEW.origin_service IS NULL OR NEW.origin_service = '' THEN
    NEW.origin_service := 'platform-api';
  END IF;

  -- Auto-compute changed_fields when not explicitly supplied by caller
  IF NEW.changed_fields IS NULL AND (
    (NEW.old_value IS NOT NULL AND jsonb_typeof(NEW.old_value) = 'object') OR
    (NEW.new_value IS NOT NULL AND jsonb_typeof(NEW.new_value) = 'object')
  ) THEN
    SELECT COALESCE(array_agg(k ORDER BY k), ARRAY[]::TEXT[])
    INTO v_diff_keys
    FROM (
      SELECT COALESCE(o.key, n.key) AS k
      FROM jsonb_each(COALESCE(NEW.old_value, '{}'::jsonb)) o
      FULL OUTER JOIN jsonb_each(COALESCE(NEW.new_value, '{}'::jsonb)) n
        ON o.key = n.key
      WHERE o.value IS DISTINCT FROM n.value
    ) diff_sub;

    IF array_length(v_diff_keys, 1) > 0 THEN
      NEW.changed_fields := v_diff_keys;
    END IF;
  END IF;

  -- Fetch previous row_hash for tamper-evident chain
  SELECT h.row_hash
  INTO v_prev_hash
  FROM public.hq_audit_logs h
  WHERE h.row_hash IS NOT NULL
  ORDER BY h.seq_no DESC
  LIMIT 1;

  NEW.prev_hash := COALESCE(v_prev_hash, 'GENESIS');

  v_canonical := concat_ws(
    '|',
    NEW.id::TEXT,
    to_char(NEW.created_at AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"'),
    COALESCE(NEW.user_id::TEXT, ''),
    COALESCE(NEW.user_email, ''),
    COALESCE(NEW.actor_type, ''),
    COALESCE(NEW.tenant_org_id::TEXT, ''),
    COALESCE(NEW.action, ''),
    COALESCE(NEW.resource_type, ''),
    COALESCE(NEW.resource_id, ''),
    COALESCE(NEW.old_value::TEXT, ''),
    COALESCE(NEW.new_value::TEXT, ''),
    COALESCE(NEW.change_reason, ''),
    NEW.prev_hash
  );

  NEW.row_hash := encode(pg_catalog.sha256(convert_to(v_canonical, 'UTF8')), 'hex');

  RETURN NEW;
END;
$$;

