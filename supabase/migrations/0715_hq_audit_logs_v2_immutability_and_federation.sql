-- Backfill row_hash & changed_fields on existing rows that lack row_hash
DO $$
DECLARE
  r RECORD;
  v_prev TEXT := 'GENESIS';
  v_canon TEXT;
  v_hash TEXT;
  v_diff TEXT[];
BEGIN
  FOR r IN
    SELECT *
    FROM public.hq_audit_logs
    ORDER BY created_at ASC NULLS FIRST, id ASC
  LOOP
    v_diff := r.changed_fields;
    IF v_diff IS NULL AND (
      (r.old_value IS NOT NULL AND jsonb_typeof(r.old_value) = 'object') OR
      (r.new_value IS NOT NULL AND jsonb_typeof(r.new_value) = 'object')
    ) THEN
      SELECT COALESCE(array_agg(k ORDER BY k), NULL)
      INTO v_diff
      FROM (
        SELECT COALESCE(o.key, n.key) AS k
        FROM jsonb_each(COALESCE(r.old_value, '{}'::jsonb)) o
        FULL OUTER JOIN jsonb_each(COALESCE(r.new_value, '{}'::jsonb)) n
          ON o.key = n.key
        WHERE o.value IS DISTINCT FROM n.value
      ) d;
    END IF;

    v_canon := concat_ws(
      '|',
      r.id::TEXT,
      to_char(COALESCE(r.created_at, now()) AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"'),
      COALESCE(r.user_id::TEXT, ''),
      COALESCE(r.user_email, ''),
      COALESCE(r.actor_type, ''),
      COALESCE(r.tenant_org_id::TEXT, ''),
      COALESCE(r.action, ''),
      COALESCE(r.resource_type, ''),
      COALESCE(r.resource_id, ''),
      COALESCE(r.old_value::TEXT, ''),
      COALESCE(r.new_value::TEXT, ''),
      COALESCE(r.change_reason, ''),
      v_prev
    );
    v_hash := encode(pg_catalog.sha256(convert_to(v_canon, 'UTF8')), 'hex');

    UPDATE public.hq_audit_logs
    SET
      prev_hash = v_prev,
      row_hash = v_hash,
      changed_fields = COALESCE(changed_fields, v_diff)
    WHERE id = r.id;

    v_prev := v_hash;
  END LOOP;
END $$;

-- ---------------------------------------------------------------------------
-- 3. BEFORE UPDATE OR DELETE Trigger: Enforce Append-Only Immutability
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.fn_hq_audit_prevent_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  -- Allow controlled cold-storage archival only when session GUC is explicitly enabled
  IF current_setting('app.audit_archival_mode', true) = 'on' THEN
    IF TG_OP = 'DELETE' THEN
      RETURN OLD;
    END IF;
    RETURN NEW;
  END IF;

  RAISE EXCEPTION 'AUDIT_IMMUTABLE_VIOLATION: public.hq_audit_logs is append-only. % operations are prohibited.', TG_OP
    USING ERRCODE = '42501';
END;
$$;

DROP TRIGGER IF EXISTS trg_hq_audit_prevent_mutation ON public.hq_audit_logs;
CREATE TRIGGER trg_hq_audit_prevent_mutation
  BEFORE UPDATE OR DELETE ON public.hq_audit_logs
  FOR EACH ROW
  EXECUTE FUNCTION public.fn_hq_audit_prevent_mutation();

