-- 4. Compliance Integrity Verification RPC (`fn_verify_hq_audit_integrity`)
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.fn_verify_hq_audit_integrity(
  p_limit INT DEFAULT 5000
)
RETURNS TABLE (
  total_checked BIGINT,
  valid_count BIGINT,
  broken_count BIGINT,
  first_broken_id UUID,
  first_broken_seq_no BIGINT,
  is_valid BOOLEAN,
  checked_at TIMESTAMPTZ
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  r RECORD;
  v_expected_prev TEXT := NULL;
  v_recomputed TEXT;
  v_total BIGINT := 0;
  v_valid BIGINT := 0;
  v_broken BIGINT := 0;
  v_first_id UUID := NULL;
  v_first_seq BIGINT := NULL;
BEGIN
  FOR r IN
    SELECT *
    FROM (
      SELECT *
      FROM public.hq_audit_logs
      ORDER BY seq_no DESC
      LIMIT GREATEST(COALESCE(p_limit, 1000), 1)
    ) recent_rows
    ORDER BY seq_no ASC
  LOOP
    v_total := v_total + 1;

    v_recomputed := encode(
      pg_catalog.sha256(
        convert_to(
          concat_ws(
            '|',
            r.id::TEXT,
            to_char(r.created_at AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"'),
            COALESCE(r.user_id::TEXT, ''),
            COALESCE(r.user_email, ''),
            COALESCE(r.actor_type, ''),
            COALESCE(r.tenant_org_id::TEXT, ''),
            COALESCE(r.action, ''),
            COALESCE(r.resource_type, ''),
            COALESCE(r.resource_id, ''),
            COALESCE(r.old_value::TEXT, ''),
            COALESCE(r.new_value::TEXT, ''),
            COALESCE(r.change_reason, ''),
            COALESCE(r.prev_hash, 'GENESIS')
          ),
          'UTF8'
        )
      ),
      'hex'
    );

    IF r.row_hash IS DISTINCT FROM v_recomputed
       OR (v_expected_prev IS NOT NULL AND r.prev_hash IS DISTINCT FROM v_expected_prev)
    THEN
      v_broken := v_broken + 1;
      IF v_first_id IS NULL THEN
        v_first_id := r.id;
        v_first_seq := r.seq_no;
      END IF;
    ELSE
      v_valid := v_valid + 1;
    END IF;

    v_expected_prev := r.row_hash;
  END LOOP;

  RETURN QUERY SELECT
    v_total,
    v_valid,
    v_broken,
    v_first_id,
    v_first_seq,
    (v_broken = 0),
    now();
END;
$$;

