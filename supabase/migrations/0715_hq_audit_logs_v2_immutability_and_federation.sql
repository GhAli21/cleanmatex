-- 5a. Mirror `sys_code_table_audit_log` inserts into `hq_audit_logs`
CREATE OR REPLACE FUNCTION public.fn_mirror_sys_code_audit_to_hq()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  INSERT INTO public.hq_audit_logs (
    user_email,
    actor_type,
    action,
    action_category,
    resource_type,
    resource_id,
    resource_label,
    old_value,
    new_value,
    changed_fields,
    change_reason,
    source_module,
    severity,
    ip_address,
    user_agent,
    origin_service,
    success,
    tags
  ) VALUES (
    COALESCE(NEW.changed_by::TEXT, 'hq_admin'),
    'hq_admin',
    'code_table.' || lower(COALESCE(NEW.action::TEXT, 'update')),
    CASE upper(COALESCE(NEW.action::TEXT, ''))
      WHEN 'INSERT' THEN 'create'
      WHEN 'DELETE' THEN 'delete'
      ELSE 'update'
    END,
    NEW.table_name::TEXT,
    NEW.record_code::TEXT,
    NEW.table_name::TEXT || ' :: ' || NEW.record_code::TEXT,
    NEW.old_values,
    NEW.new_values,
    NEW.changed_fields,
    NEW.change_reason::TEXT,
    'system-codes',
    CASE WHEN upper(COALESCE(NEW.action::TEXT, '')) = 'DELETE' THEN 'warning' ELSE 'info' END,
    NULL,
    NEW.user_agent::TEXT,
    'db-trigger',
    true,
    ARRAY['system-codes', COALESCE(NEW.table_name::TEXT, 'code')]
  );
  RETURN NEW;
EXCEPTION WHEN OTHERS THEN
  -- Never block primary transaction if mirror fails
  RETURN NEW;
END;
$$;

