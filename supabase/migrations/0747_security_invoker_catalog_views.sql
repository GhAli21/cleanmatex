-- Purpose:   Make the seven catalog views run as the caller, then close them
--            to anon and authenticated. service_role keeps select and still
--            bypasses row security, so HQ and server reads continue.
--            vw_doc_seq_consistency and vw_hq_unified_audit_trail are already
--            security_invoker and are not changed.
-- Affected:  v_effective_tenant_settings, vw_fin_coa_explorer,
--            vw_fin_effective_gov_for_tenant, vw_fin_missing_required_usage,
--            vw_fin_open_exceptions, vw_fin_tenant_readiness,
--            org_order_status_history_legacy
-- Plan:      docs/pending_to_production/16_11_2026/S0_privilege_lockdown_PLAN.md
--            Phase D. Do not edit this file after it is applied.
-- =============================================================================

BEGIN;

SET LOCAL lock_timeout = '3s';

DO $views$
DECLARE
  view_name text;
  view_names text[] := ARRAY[
    'v_effective_tenant_settings',
    'vw_fin_coa_explorer',
    'vw_fin_effective_gov_for_tenant',
    'vw_fin_missing_required_usage',
    'vw_fin_open_exceptions',
    'vw_fin_tenant_readiness',
    'org_order_status_history_legacy'
  ];
  existing_comment text;
  next_comment text;
  marker constant text := 'Runs as the caller (security_invoker).';
BEGIN
  FOREACH view_name IN ARRAY view_names LOOP
    -- PG15 can flip the option without recreating the view, so grants and
    -- dependent objects stay in place. The revoke below removes the browser roles.
    EXECUTE format('ALTER VIEW public.%I SET (security_invoker = true)', view_name);
    EXECUTE format(
      'REVOKE ALL ON TABLE public.%I FROM PUBLIC, anon, authenticated',
      view_name
    );
    EXECUTE format('GRANT SELECT ON TABLE public.%I TO service_role', view_name);

    SELECT obj_description(c.oid, 'pg_class') INTO existing_comment
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND c.relname = view_name;

    IF existing_comment IS NULL OR position(marker IN existing_comment) = 0 THEN
      next_comment := CASE
        WHEN existing_comment IS NULL OR btrim(existing_comment) = ''
          THEN marker || ' Closed to anon and authenticated. service_role keeps select.'
        ELSE existing_comment || ' ' || marker || ' Closed to anon and authenticated.'
      END;
      EXECUTE format('COMMENT ON VIEW public.%I IS %L', view_name, next_comment);
    END IF;
  END LOOP;
END
$views$;

DO $check$
DECLARE
  open_count integer;
BEGIN
  SELECT count(*) INTO open_count
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public'
    AND c.relkind = 'v'
    AND c.relname IN (
      'v_effective_tenant_settings',
      'vw_fin_coa_explorer',
      'vw_fin_effective_gov_for_tenant',
      'vw_fin_missing_required_usage',
      'vw_fin_open_exceptions',
      'vw_fin_tenant_readiness',
      'org_order_status_history_legacy'
    )
    AND (
      NOT coalesce(c.reloptions, ARRAY[]::text[]) @> ARRAY['security_invoker=true']
      OR has_table_privilege('anon', c.oid, 'SELECT')
      OR has_table_privilege('authenticated', c.oid, 'SELECT')
      OR NOT has_table_privilege('service_role', c.oid, 'SELECT')
    );

  IF open_count > 0 THEN
    RAISE EXCEPTION 's0 view lockdown failed: % of the seven views are still definer views, still granted to anon or authenticated, or lost service_role select', open_count;
  END IF;
END
$check$;

COMMIT;
