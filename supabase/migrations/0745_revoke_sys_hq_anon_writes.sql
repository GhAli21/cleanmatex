-- =============================================================================
-- Migration: 0745_revoke_sys_hq_anon_writes.sql
-- Purpose:   Close sys_*, hq_*, and crm_track_test to the public API key.
--            anon and authenticated lose every table privilege. Row security
--            is enabled and forced. postgres and service_role bypass row
--            security, so Prisma and the service-role server clients keep
--            working. There is no browser allowlist: no policy is added.
--            org_* grants and policies are not changed.
-- Affected:  every public sys_* and hq_* table, crm_track_test, the sequences
--            those tables own, and default privileges of postgres (and of
--            supabase_admin when the applying role is allowed to change them)
-- Plan:      docs/pending_to_production/16_11_2026/S0_privilege_lockdown_PLAN.md
--            Phase B. Do not edit this file after it is applied.
-- =============================================================================

BEGIN;

SET LOCAL lock_timeout = '3s';

-- Catalog tables are not tenant rows. The app reads them with the service role
-- after its own authorization check. No browser policy is added. Force is on so
-- a future non-bypass role cannot read these tables through a missing policy.
DO $tables$
DECLARE
  target record;
  existing_comment text;
  next_comment text;
  marker constant text := 'Closed to the public key';
BEGIN
  FOR target IN
    SELECT c.oid, c.relname
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND c.relkind = 'r'
      AND (
        c.relname LIKE 'sys\_%' ESCAPE '\'
        OR c.relname LIKE 'hq\_%' ESCAPE '\'
        OR c.relname = 'crm_track_test'
      )
  LOOP
    -- Removes select as well as write. BYPASSRLS does not bypass a missing grant.
    EXECUTE format(
      'REVOKE ALL ON TABLE public.%I FROM PUBLIC, anon, authenticated',
      target.relname
    );
    EXECUTE format(
      'GRANT ALL ON TABLE public.%I TO service_role',
      target.relname
    );
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', target.relname);
    EXECUTE format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY', target.relname);

    existing_comment := obj_description(target.oid, 'pg_class');
    IF existing_comment IS NULL OR position(marker IN existing_comment) = 0 THEN
      next_comment := CASE
        WHEN existing_comment IS NULL OR btrim(existing_comment) = ''
          THEN marker || '. anon and authenticated have no privileges. service_role keeps full access and bypasses row security. No browser policy.'
        ELSE existing_comment || ' ' || marker || '. anon and authenticated have no privileges; service_role keeps access.'
      END;
      EXECUTE format('COMMENT ON TABLE public.%I IS %L', target.relname, next_comment);
    END IF;
  END LOOP;
END
$tables$;

-- Identity and serial sequences follow the table. nextval is a write.
DO $sequences$
DECLARE
  seq_name text;
BEGIN
  FOR seq_name IN
    SELECT s.relname
    FROM pg_class s
    JOIN pg_namespace sn ON sn.oid = s.relnamespace
    JOIN pg_depend d ON d.objid = s.oid AND d.deptype IN ('a', 'i')
    JOIN pg_class t ON t.oid = d.refobjid
    JOIN pg_namespace tn ON tn.oid = t.relnamespace
    WHERE sn.nspname = 'public'
      AND tn.nspname = 'public'
      AND s.relkind = 'S'
      AND (
        t.relname LIKE 'sys\_%' ESCAPE '\'
        OR t.relname LIKE 'hq\_%' ESCAPE '\'
        OR t.relname = 'crm_track_test'
      )
  LOOP
    EXECUTE format(
      'REVOKE ALL ON SEQUENCE public.%I FROM PUBLIC, anon, authenticated',
      seq_name
    );
    EXECUTE format('GRANT ALL ON SEQUENCE public.%I TO service_role', seq_name);
  END LOOP;
END
$sequences$;

-- Future objects created by migration role postgres must not reopen the public key.
-- org_* migrations have to GRANT the privileges they actually need.
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public
  REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public
  REVOKE ALL ON SEQUENCES FROM PUBLIC, anon, authenticated;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public
  GRANT ALL ON TABLES TO service_role;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public
  GRANT ALL ON SEQUENCES TO service_role;

-- Dashboard SQL runs as supabase_admin. postgres is not a member of that role
-- on the hosted database, so this is attempted and skipped with a notice when
-- the applying role cannot change it. The owner then runs
-- scripts/db/s0-supabase-admin-default-privileges.sql in the SQL editor.
DO $admin_defaults$
BEGIN
  IF pg_has_role(current_user, 'supabase_admin', 'MEMBER') THEN
    EXECUTE 'ALTER DEFAULT PRIVILEGES FOR ROLE supabase_admin IN SCHEMA public REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated';
    EXECUTE 'ALTER DEFAULT PRIVILEGES FOR ROLE supabase_admin IN SCHEMA public REVOKE ALL ON SEQUENCES FROM PUBLIC, anon, authenticated';
    EXECUTE 'ALTER DEFAULT PRIVILEGES FOR ROLE supabase_admin IN SCHEMA public GRANT ALL ON TABLES TO service_role';
    EXECUTE 'ALTER DEFAULT PRIVILEGES FOR ROLE supabase_admin IN SCHEMA public GRANT ALL ON SEQUENCES TO service_role';
  ELSE
    RAISE NOTICE 's0: current_user % cannot change supabase_admin default privileges. Run scripts/db/s0-supabase-admin-default-privileges.sql as supabase_admin.', current_user;
  END IF;
END
$admin_defaults$;

DO $check$
DECLARE
  open_count integer;
BEGIN
  SELECT count(*) INTO open_count
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public'
    AND c.relkind = 'r'
    AND (
      c.relname LIKE 'sys\_%' ESCAPE '\'
      OR c.relname LIKE 'hq\_%' ESCAPE '\'
      OR c.relname = 'crm_track_test'
    )
    AND (
      has_table_privilege('anon', c.oid, 'SELECT')
      OR has_table_privilege('anon', c.oid, 'INSERT')
      OR has_table_privilege('anon', c.oid, 'UPDATE')
      OR has_table_privilege('anon', c.oid, 'DELETE')
      OR has_table_privilege('authenticated', c.oid, 'SELECT')
      OR has_table_privilege('authenticated', c.oid, 'INSERT')
      OR has_table_privilege('authenticated', c.oid, 'UPDATE')
      OR has_table_privilege('authenticated', c.oid, 'DELETE')
      OR NOT c.relrowsecurity
      OR NOT c.relforcerowsecurity
      OR NOT has_table_privilege('service_role', c.oid, 'SELECT')
    );

  IF open_count > 0 THEN
    RAISE EXCEPTION 's0 table lockdown failed: % sys_*/hq_*/crm_track_test tables are still open to anon or authenticated, or are missing forced row security, or lost service_role select', open_count;
  END IF;
END
$check$;

COMMIT;
