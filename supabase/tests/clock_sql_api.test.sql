-- ==================================================================
-- clock_sql_api.test.sql
-- Purpose: S2 checks for the clock SQL API (MASTER_PLAN_v2 §5, §10 T-rows): our clock and the gated
--          test override, the zone catalog (D28, D32), zone resolution with notify (D27), the zone
--          validators (G20), the civil/instant functions, the settings readers (D33, D34), the
--          business date (D6), grants (§7.16) and health (§5.3).
-- Dependencies: 0842_cmx_dt_clock_api.sql and 0843_cmx_dt_settings.sql.
-- Run (LOCAL database only, as the postgres/superuser role so SET ROLE and the test clock work):
--   psql "$LOCAL_DB_URL" -v ON_ERROR_STOP=1 -f supabase/tests/clock_sql_api.test.sql
-- Needs at least 2 rows in org_tenants_mst; branch checks run when tenant A has a branch.
-- Everything runs in one transaction and is ROLLED BACK at the end: no data or setting is kept
-- (the test sets cmx_dt_env_cf to the test value inside the transaction only).
-- Each test prints "PASS: ..." or stops with "FAIL: ...". pgTAP is not installed in this repo, so the
-- file follows the plain-SQL style of the other supabase/tests files.
-- Sections and the plan's test names (§7.1.1 matrix): 1 clock_fake_now_gate (T54, T66); 2 clock_catalog
-- (T61, D32); 3 clock_zone_validators (T62, T63); 4 clock_sql_api; 5 clock_settings (T52, T53, T65 with
-- fixed values); 6 clock_grants_safety (§7.16); 7 clock_health_registry (T64). The shared vectors run in
-- clock_vectors.test.sql (generated by scripts/gen-clock-vectors-sql.mjs).
-- ==================================================================

BEGIN;
SET LOCAL lock_timeout = '5s';

CREATE TEMP TABLE zz_ctx (k TEXT PRIMARY KEY, v TEXT) ON COMMIT DROP;
GRANT SELECT ON zz_ctx TO PUBLIC;

-- Returns the error message of p_sql, or NULL when it ran without error.
CREATE FUNCTION pg_temp.zz_err(p_sql TEXT) RETURNS TEXT LANGUAGE plpgsql AS $$
BEGIN
  EXECUTE p_sql;
  RETURN NULL;
EXCEPTION WHEN OTHERS THEN
  RETURN SQLSTATE || ' ' || SQLERRM;
END $$;

-- ------------------------------------------------------------------
-- Fixture: tenant A (with a branch when one exists) and tenant B; values set here are rolled back.
-- ------------------------------------------------------------------
DO $$
DECLARE
  v_a UUID; v_b UUID; v_br UUID; v_user UUID;
BEGIN
  SELECT ou.tenant_org_id, ou.user_id INTO v_a, v_user
    FROM public.org_users_mst ou JOIN public.org_tenants_mst t ON t.id = ou.tenant_org_id
   WHERE ou.is_active AND ou.user_id IS NOT NULL
   LIMIT 1;
  IF v_a IS NULL THEN
    SELECT id INTO v_a FROM public.org_tenants_mst ORDER BY id LIMIT 1;
  END IF;
  SELECT id INTO v_b FROM public.org_tenants_mst WHERE id <> v_a ORDER BY id LIMIT 1;
  IF v_a IS NULL OR v_b IS NULL THEN
    RAISE EXCEPTION 'SETUP: need at least 2 tenants in org_tenants_mst';
  END IF;
  SELECT id INTO v_br FROM public.org_branches_mst WHERE tenant_org_id = v_a ORDER BY id LIMIT 1;
  UPDATE public.org_tenants_mst
     SET timezone = 'Asia/Muscat', country = 'OM', time_format = NULL, first_day_of_week = NULL,
         date_format = NULL, fiscal_year_start_month = 4, business_day_cutover = NULL
   WHERE id = v_a;
  UPDATE public.org_tenants_mst SET timezone = 'Asia/Kolkata' WHERE id = v_b;
  IF v_br IS NOT NULL THEN
    UPDATE public.org_branches_mst SET timezone_code = 'Asia/Dubai', business_day_cutover = NULL, is_active = true WHERE id = v_br;
  END IF;
  INSERT INTO zz_ctx VALUES ('a', v_a::text), ('b', v_b::text), ('br', v_br::text), ('user', v_user::text);
  RAISE NOTICE 'SETUP: tenant A %, tenant B %, branch of A %, member user of A %', v_a, v_b,
    coalesce(v_br::text, '<none: branch checks skipped>'), coalesce(v_user::text, '<none>');
END $$;

-- ------------------------------------------------------------------
-- 1. Clock (D25) and the gated test override (§5.0, T66)
-- ------------------------------------------------------------------
DO $$
DECLARE v_err TEXT;
BEGIN
  IF public.fn_cmx_dt_now() <> pg_catalog.now() THEN RAISE EXCEPTION 'FAIL 1a: fn_cmx_dt_now differs from the transaction time'; END IF;
  IF public.fn_cmx_dt_clock() < pg_catalog.now() THEN RAISE EXCEPTION 'FAIL 1b: fn_cmx_dt_clock is before the transaction time'; END IF;
  IF (SELECT env FROM public.cmx_dt_env_cf WHERE config_id) IS DISTINCT FROM 'prod' THEN RAISE EXCEPTION 'FAIL 1c: env is not prod'; END IF;
  -- prod: the override is ignored (with a WARNING).
  PERFORM set_config('cmx.fake_now', '2030-01-01T00:00:00Z', true);
  IF public.fn_cmx_dt_now() <> pg_catalog.now() THEN RAISE EXCEPTION 'FAIL 1d: fake clock honoured in prod'; END IF;
  -- test env: honoured for the superuser session.
  UPDATE public.cmx_dt_env_cf SET env = 'test' WHERE config_id;
  IF public.fn_cmx_dt_now() <> TIMESTAMPTZ '2030-01-01 00:00:00+00' THEN RAISE EXCEPTION 'FAIL 1e: fake clock not honoured in test env'; END IF;
  IF public.fn_cmx_dt_clock() < TIMESTAMPTZ '2030-01-01 00:00:00+00' THEN RAISE EXCEPTION 'FAIL 1f: fake moving clock'; END IF;
  IF public.fn_cmx_dt_today_in('Asia/Muscat') <> DATE '2030-01-01' THEN RAISE EXCEPTION 'FAIL 1g: default p_at ignores the fake clock'; END IF;
  -- a value without an offset is ignored.
  PERFORM set_config('cmx.fake_now', '2030-01-01 00:00:00', true);
  IF public.fn_cmx_dt_now() <> pg_catalog.now() THEN RAISE EXCEPTION 'FAIL 1h: offset-less fake value honoured'; END IF;
  PERFORM set_config('cmx.fake_now', '2030-01-01T00:00:00+04:00', true);
  -- an app role is never faked, even in the test env.
  SET LOCAL ROLE authenticated;
  IF public.fn_cmx_dt_now() <> pg_catalog.now() THEN RESET ROLE; RAISE EXCEPTION 'FAIL 1i: fake clock honoured for authenticated'; END IF;
  RESET ROLE;
  SET LOCAL ROLE anon;
  IF public.fn_cmx_dt_now() <> pg_catalog.now() THEN RESET ROLE; RAISE EXCEPTION 'FAIL 1j: fake clock honoured for anon'; END IF;
  RESET ROLE;
  -- health sees the test env.
  IF NOT EXISTS (SELECT 1 FROM public.fn_cmx_dt_chk_fake_env(NULL)) THEN RAISE EXCEPTION 'FAIL 1k: CLOCK_FAKE_ENV not reported'; END IF;
  PERFORM set_config('cmx.fake_now', '', true);
  UPDATE public.cmx_dt_env_cf SET env = 'prod' WHERE config_id;
  IF EXISTS (SELECT 1 FROM public.fn_cmx_dt_chk_fake_env(NULL)) THEN RAISE EXCEPTION 'FAIL 1l: CLOCK_FAKE_ENV after reset'; END IF;
  v_err := pg_temp.zz_err($q$UPDATE public.cmx_dt_env_cf SET env = 'staging' WHERE config_id$q$);
  IF v_err IS NULL OR v_err NOT LIKE '23514%' THEN RAISE EXCEPTION 'FAIL 1m: env CHECK, got %', v_err; END IF;
  RAISE NOTICE 'PASS 1: clock, test-clock gate (prod, test, offset, app roles), CLOCK_FAKE_ENV';
END $$;

-- ------------------------------------------------------------------
-- 2. Zone catalog (D28, D32) and its integrity trigger
-- ------------------------------------------------------------------
DO $$
DECLARE v_err TEXT;
BEGIN
  IF NOT public.fn_cmx_dt_is_valid_zone('Asia/Muscat') OR public.fn_cmx_dt_canonical_zone('Asia/Muscat') <> 'Asia/Muscat' THEN
    RAISE EXCEPTION 'FAIL 2a: Asia/Muscat must be canonical and valid (D32)'; END IF;
  IF EXISTS (SELECT 1 FROM public.sys_timezone_cd WHERE code IN ('Asia/Kuwait', 'Asia/Bahrain', 'Asia/Aden', 'Asia/Qatar', 'Asia/Riyadh', 'Asia/Dubai', 'UTC') AND NOT is_canonical) THEN
    RAISE EXCEPTION 'FAIL 2b: a Gulf zone or UTC is an alias'; END IF;
  IF public.fn_cmx_dt_canonical_zone('Asia/Calcutta') <> 'Asia/Kolkata' OR NOT public.fn_cmx_dt_is_valid_zone('Asia/Calcutta') THEN
    RAISE EXCEPTION 'FAIL 2c: Asia/Calcutta must be a valid alias of Asia/Kolkata'; END IF;
  IF public.fn_cmx_dt_canonical_zone('Etc/UTC') <> 'UTC' OR public.fn_cmx_dt_canonical_zone('Zulu') <> 'UTC' THEN
    RAISE EXCEPTION 'FAIL 2d: UTC family must normalize to UTC'; END IF;
  IF public.fn_cmx_dt_is_valid_zone('EST') OR public.fn_cmx_dt_is_valid_zone('Etc/GMT-4') OR public.fn_cmx_dt_is_valid_zone('+04:00')
     OR public.fn_cmx_dt_is_valid_zone('') OR public.fn_cmx_dt_is_valid_zone(NULL) OR public.fn_cmx_dt_is_valid_zone('asia/muscat') THEN
    RAISE EXCEPTION 'FAIL 2e: abbreviation / offset / empty / wrong-case name accepted'; END IF;
  IF EXISTS (SELECT 1 FROM public.sys_timezone_cd WHERE NOT is_canonical AND is_active) THEN
    RAISE EXCEPTION 'FAIL 2f: an alias row is active'; END IF;
  IF EXISTS (SELECT 1 FROM public.sys_timezone_cd a LEFT JOIN public.sys_timezone_cd c ON c.code = a.link_target
              WHERE NOT a.is_canonical AND (c.code IS NULL OR NOT c.is_canonical OR a.iana_name <> a.link_target)) THEN
    RAISE EXCEPTION 'FAIL 2g: alias rows must point at canonical rows'; END IF;
  IF EXISTS (SELECT 1 FROM public.sys_timezone_cd WHERE is_canonical AND (iana_name <> code OR link_target IS NOT NULL)) THEN
    RAISE EXCEPTION 'FAIL 2h: canonical rows must have iana_name = code'; END IF;
  v_err := pg_temp.zz_err($q$INSERT INTO public.sys_timezone_cd (code, name, utc_offset_hours, iana_name, std_offset_minutes, dst_offset_minutes, tzdb_version)
                             VALUES ('EST', 'EST', -5, 'EST', -300, -300, 'x')$q$);
  IF v_err IS NULL OR v_err NOT LIKE '%CLOCK_CATALOG_BAD_NAME%' THEN RAISE EXCEPTION 'FAIL 2i: EST row accepted (%)', v_err; END IF;
  v_err := pg_temp.zz_err($q$UPDATE public.sys_timezone_cd SET is_active = true WHERE code = 'Asia/Calcutta'$q$);
  IF v_err IS NULL OR v_err NOT LIKE '%CLOCK_CATALOG_BAD_LINK%' THEN RAISE EXCEPTION 'FAIL 2j: alias activated (%)', v_err; END IF;
  v_err := pg_temp.zz_err($q$UPDATE public.sys_timezone_cd SET is_canonical = false, link_target = 'Asia/Dubai', iana_name = 'Asia/Dubai', is_active = false WHERE code = 'Asia/Kolkata'$q$);
  IF v_err IS NULL OR v_err NOT LIKE '%CLOCK_CATALOG_BAD_LINK%' THEN RAISE EXCEPTION 'FAIL 2k: canonical with aliases demoted (%)', v_err; END IF;
  IF EXISTS (SELECT 1 FROM public.fn_cmx_dt_chk_catalog_unknown(NULL)) THEN
    RAISE NOTICE 'NOTE 2: active catalog zones unknown to this Postgres: %', (SELECT string_agg(detail ->> 'zone', ', ') FROM public.fn_cmx_dt_chk_catalog_unknown(NULL));
  END IF;
  RAISE NOTICE 'PASS 2: catalog canonical rule, aliases, integrity trigger';
END $$;

-- ------------------------------------------------------------------
-- 3. Zone resolution (D26, D27) and validators (G20)
-- ------------------------------------------------------------------
DO $$
DECLARE
  v_a  UUID := (SELECT v::uuid FROM zz_ctx WHERE k = 'a');
  v_br UUID := (SELECT nullif(v, '')::uuid FROM zz_ctx WHERE k = 'br');
  v_err TEXT; v_op TEXT;
BEGIN
  FOREACH v_op IN ARRAY public.fn_cmx_dt_operations() LOOP
    IF public.fn_cmx_dt_zone(v_a, v_op, NULL) IS DISTINCT FROM 'Asia/Muscat' THEN RAISE EXCEPTION 'FAIL 3a: % zone', v_op; END IF;
  END LOOP;
  IF NOT ('notify' = ANY (public.fn_cmx_dt_operations())) OR public.fn_ops_zone(v_a, 'notify', NULL) IS DISTINCT FROM 'Asia/Muscat' THEN
    RAISE EXCEPTION 'FAIL 3b: notify not accepted by fn_ops_zone'; END IF;
  v_err := pg_temp.zz_err(format('SELECT public.fn_cmx_dt_zone(%L, %L, NULL)', v_a, 'acept_order'));
  IF v_err IS NULL OR v_err NOT LIKE '22023 CLOCK_UNKNOWN_OPERATION%' THEN RAISE EXCEPTION 'FAIL 3c: typo operation gave %', v_err; END IF;
  IF v_br IS NOT NULL THEN
    IF public.fn_cmx_dt_zone(v_a, 'accept_order', v_br) <> 'Asia/Dubai' THEN RAISE EXCEPTION 'FAIL 3d: branch zone not used'; END IF;
    UPDATE public.org_branches_mst SET timezone_code = 'Asia/Calcutta' WHERE id = v_br;
    IF (SELECT timezone_code FROM public.org_branches_mst WHERE id = v_br) <> 'Asia/Kolkata' THEN RAISE EXCEPTION 'FAIL 3e: branch alias not normalized'; END IF;
    v_err := pg_temp.zz_err(format('UPDATE public.org_branches_mst SET timezone_code = %L WHERE id = %L', 'EST', v_br));
    IF v_err IS NULL OR v_err NOT LIKE '%HQ_CONFIG_BAD_TIMEZONE%' AND v_err NOT LIKE '23503%' THEN RAISE EXCEPTION 'FAIL 3f: branch EST accepted (%)', v_err; END IF;
    UPDATE public.org_branches_mst SET timezone_code = NULL WHERE id = v_br;
    IF public.fn_cmx_dt_zone(v_a, 'accept_order', v_br) <> 'Asia/Muscat' THEN RAISE EXCEPTION 'FAIL 3g: branch NULL must inherit'; END IF;
    UPDATE public.org_branches_mst SET timezone_code = 'Asia/Dubai' WHERE id = v_br;
  END IF;
  UPDATE public.org_tenants_mst SET timezone = 'Asia/Calcutta' WHERE id = v_a;
  IF (SELECT timezone FROM public.org_tenants_mst WHERE id = v_a) <> 'Asia/Kolkata' THEN RAISE EXCEPTION 'FAIL 3h: tenant alias not normalized'; END IF;
  v_err := pg_temp.zz_err(format('UPDATE public.org_tenants_mst SET timezone = %L WHERE id = %L', 'Mars/Olympus', v_a));
  IF v_err IS NULL OR v_err NOT LIKE '22023 HQ_CONFIG_BAD_TIMEZONE%' THEN RAISE EXCEPTION 'FAIL 3i: unknown tenant zone accepted (%)', v_err; END IF;
  v_err := pg_temp.zz_err($q$UPDATE public.hq_general_config SET timezone = 'GMT+4' WHERE config_id$q$);
  IF v_err IS NULL OR v_err NOT LIKE '22023 HQ_CONFIG_BAD_TIMEZONE%' THEN RAISE EXCEPTION 'FAIL 3j: HQ GMT+4 accepted (%)', v_err; END IF;
  -- An inactive catalog row is not accepted for new values.
  UPDATE public.sys_timezone_cd SET is_active = false WHERE code = 'Asia/Pyongyang';
  v_err := pg_temp.zz_err(format('UPDATE public.org_tenants_mst SET timezone = %L WHERE id = %L', 'Asia/Pyongyang', v_a));
  IF v_err IS NULL THEN RAISE EXCEPTION 'FAIL 3k: inactive zone accepted'; END IF;
  UPDATE public.sys_timezone_cd SET is_active = true WHERE code = 'Asia/Pyongyang';
  UPDATE public.org_tenants_mst SET timezone = 'Asia/Muscat' WHERE id = v_a;
  -- Missing zone: fail closed.
  UPDATE public.org_tenants_mst SET timezone = NULL WHERE id = v_a;
  IF public.fn_cmx_dt_zone(v_a, 'ledger', NULL) IS NOT NULL OR public.fn_cmx_dt_today_or_null(v_a, 'ledger') IS NOT NULL THEN
    RAISE EXCEPTION 'FAIL 3l: missing zone must give NULL'; END IF;
  v_err := pg_temp.zz_err(format('SELECT public.fn_cmx_dt_today(%L, %L)', v_a, 'ledger'));
  IF v_err IS NULL OR v_err NOT LIKE 'P0001 TIMEZONE_NOT_CONFIGURED%' THEN RAISE EXCEPTION 'FAIL 3m: missing zone gave %', v_err; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.fn_cmx_dt_chk_zone_missing(v_a)) THEN RAISE EXCEPTION 'FAIL 3n: CLOCK_ZONE_MISSING not reported'; END IF;
  UPDATE public.org_tenants_mst SET timezone = 'Asia/Muscat' WHERE id = v_a;
  IF EXISTS (SELECT 1 FROM public.fn_cmx_dt_chk_zone_missing(v_a)) THEN RAISE EXCEPTION 'FAIL 3o: CLOCK_ZONE_MISSING after fix'; END IF;
  RAISE NOTICE 'PASS 3: zone resolution, notify, unknown operation, validators normalize and reject, fail closed';
END $$;

-- ------------------------------------------------------------------
-- 4. Civil and instant functions (§5.1; the full vector set is clock_vectors.test.sql)
-- ------------------------------------------------------------------
DO $$
DECLARE
  v_a UUID := (SELECT v::uuid FROM zz_ctx WHERE k = 'a');
  v_err TEXT; r RECORD;
BEGIN
  IF public.fn_cmx_dt_today(v_a, 'accept_order', NULL, TIMESTAMPTZ '2026-11-26 21:00:00+00') <> DATE '2026-11-27' THEN
    RAISE EXCEPTION 'FAIL 4a: Muscat 01:00 on the 27th'; END IF;
  IF public.fn_cmx_dt_local_time(v_a, 'accept_order', NULL, TIMESTAMPTZ '2026-11-26 18:06:00+00') <> TIME '22:06' THEN
    RAISE EXCEPTION 'FAIL 4b: local time'; END IF;
  IF public.fn_cmx_dt_at_local(v_a, 'accept_order', NULL, DATE '2026-11-27', TIME '09:00') <> TIMESTAMPTZ '2026-11-27 05:00:00+00' THEN
    RAISE EXCEPTION 'FAIL 4c: at_local Muscat'; END IF;
  -- New York 2026-03-08 02:30 is in the spring gap; 2026-11-01 01:30 is in the autumn overlap.
  v_err := pg_temp.zz_err($q$SELECT public.fn_cmx_dt_instant_at_zone('America/New_York', '2026-03-08', '02:30')$q$);
  IF v_err IS NULL OR v_err NOT LIKE 'P0001 LOCAL_TIME_NONEXISTENT%' THEN RAISE EXCEPTION 'FAIL 4d: gap reject gave %', v_err; END IF;
  IF public.fn_cmx_dt_instant_at_zone('America/New_York', '2026-03-08', '02:30', 'compatible') <> TIMESTAMPTZ '2026-03-08 07:30:00+00' THEN
    RAISE EXCEPTION 'FAIL 4e: gap compatible'; END IF;
  v_err := pg_temp.zz_err($q$SELECT public.fn_cmx_dt_instant_at_zone('America/New_York', '2026-11-01', '01:30')$q$);
  IF v_err IS NULL OR v_err NOT LIKE 'P0001 LOCAL_TIME_AMBIGUOUS%' THEN RAISE EXCEPTION 'FAIL 4f: overlap reject gave %', v_err; END IF;
  IF public.fn_cmx_dt_instant_at_zone('America/New_York', '2026-11-01', '01:30', 'earlier') <> TIMESTAMPTZ '2026-11-01 05:30:00+00'
     OR public.fn_cmx_dt_instant_at_zone('America/New_York', '2026-11-01', '01:30', 'later') <> TIMESTAMPTZ '2026-11-01 06:30:00+00' THEN
    RAISE EXCEPTION 'FAIL 4g: overlap earlier/later'; END IF;
  SELECT * INTO r FROM public.fn_cmx_dt_day_bounds_in('America/New_York', '2026-03-08', '2026-03-09');
  IF r.end_at - r.start_at <> INTERVAL '23 hours' THEN RAISE EXCEPTION 'FAIL 4h: 23-hour day'; END IF;
  IF public.fn_cmx_dt_civil_add('2026-01-31', 1, 'MONTH') <> DATE '2026-02-28' THEN RAISE EXCEPTION 'FAIL 4i: month end clamp'; END IF;
  IF public.fn_cmx_dt_to_local(TIMESTAMPTZ '2026-11-26 18:06:00+00', 'Asia/Muscat') <> TIMESTAMP '2026-11-26 22:06:00' THEN  -- CIVIL: expected wall time
    RAISE EXCEPTION 'FAIL 4j: to_local'; END IF;
  IF (SELECT p.utc_offset_min FROM public.fn_cmx_dt_local_parts(TIMESTAMPTZ '2026-11-26 18:06:00+00', 'Asia/Muscat') p) <> 240 THEN
    RAISE EXCEPTION 'FAIL 4k: local_parts offset'; END IF;
  -- Zone-dependent functions stay STABLE (§11 row 47); only civil_add and the pure resolvers are IMMUTABLE.
  IF EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
              WHERE n.nspname = 'public' AND p.proname LIKE 'fn\_cmx\_dt\_%' AND p.provolatile = 'i'
                AND p.proname !~ '^fn_cmx_dt_(civil_add|operations|_resolve_\w+|_check_cutover)$') THEN
    RAISE EXCEPTION 'FAIL 4l: an unexpected IMMUTABLE clock function: %', (SELECT string_agg(p.proname, ', ') FROM pg_proc p
      WHERE p.proname LIKE 'fn\_cmx\_dt\_%' AND p.provolatile = 'i' AND p.proname !~ '^fn_cmx_dt_(civil_add|operations|_resolve_\w+|_check_cutover)$'); END IF;
  RAISE NOTICE 'PASS 4: today, local time, at_local, gap/overlap, 23-hour day, civil add, to_local, local_parts';
END $$;

-- ------------------------------------------------------------------
-- 5. Settings readers (D33, D34), business date (D6), period keys
-- ------------------------------------------------------------------
DO $$
DECLARE
  v_a  UUID := (SELECT v::uuid FROM zz_ctx WHERE k = 'a');
  v_br UUID := (SELECT nullif(v, '')::uuid FROM zz_ctx WHERE k = 'br');
  v_cc TEXT; s RECORD; v_err TEXT;
BEGIN
  -- Country step: give OM known defaults inside this transaction so the test does not depend on CLDR values.
  UPDATE public.sys_country_cd SET default_hour_cycle = 'H12', default_week_start = 6 WHERE code = 'OM';
  IF NOT FOUND THEN RAISE EXCEPTION 'SETUP: sys_country_cd has no OM row'; END IF;
  SELECT * INTO s FROM public.fn_cmx_dt_settings(v_a);
  IF s.hour_cycle <> 'h12' OR s.hour_cycle_source <> 'country' OR s.week_start <> 6 OR s.week_start_source <> 'country' THEN
    RAISE EXCEPTION 'FAIL 5a: country step (%)', row_to_json(s); END IF;
  IF s.cutover_source <> 'platform' OR s.date_format_source <> 'platform' THEN RAISE EXCEPTION 'FAIL 5b: platform step'; END IF;
  UPDATE public.org_tenants_mst SET time_format = '24h', first_day_of_week = 0, date_format = 'YYYY-MM-DD', business_day_cutover = '03:00' WHERE id = v_a;
  SELECT * INTO s FROM public.fn_cmx_dt_settings(v_a);
  IF s.hour_cycle <> 'h23' OR s.week_start <> 7 OR s.date_format <> 'YYYY-MM-DD' OR s.cutover <> TIME '03:00' OR s.cutover_source <> 'tenant' THEN
    RAISE EXCEPTION 'FAIL 5c: tenant step (%)', row_to_json(s); END IF;
  IF public.fn_cmx_dt_hour_cycle(v_a) <> 'h23' OR public.fn_cmx_dt_week_start(v_a) <> 7
     OR public.fn_cmx_dt_date_format(v_a) <> 'YYYY-MM-DD' OR public.fn_cmx_dt_cutover(v_a) <> TIME '03:00' THEN
    RAISE EXCEPTION 'FAIL 5d: single readers'; END IF;
  -- Business date: Muscat 02:00 local on the 27th with cut-over 03:00 belongs to the 26th.
  IF public.fn_cmx_dt_business_date(v_a, 'pos_session', NULL, TIMESTAMPTZ '2026-11-26 22:00:00+00') <> DATE '2026-11-26' THEN
    RAISE EXCEPTION 'FAIL 5e: business date'; END IF;
  IF (SELECT b.start_at FROM public.fn_cmx_dt_business_day_bounds(v_a, 'pos_session', NULL, '2026-11-27', '2026-11-28') b)
     <> TIMESTAMPTZ '2026-11-26 23:00:00+00' THEN RAISE EXCEPTION 'FAIL 5f: business day bounds'; END IF;
  v_err := pg_temp.zz_err(format('UPDATE public.org_tenants_mst SET business_day_cutover = %L WHERE id = %L', '12:00', v_a));
  IF v_err IS NULL OR v_err NOT LIKE '23514%' THEN RAISE EXCEPTION 'FAIL 5g: cut-over 12:00 accepted (%)', v_err; END IF;
  IF v_br IS NOT NULL THEN
    UPDATE public.org_branches_mst SET business_day_cutover = '05:30' WHERE id = v_br;
    IF public.fn_cmx_dt_cutover(v_a, v_br) <> TIME '05:30' THEN RAISE EXCEPTION 'FAIL 5h: branch cut-over'; END IF;
    -- Dubai 05:00 local on the 27th is before the 05:30 branch cut-over.
    IF public.fn_cmx_dt_business_date(v_a, 'pos_session', v_br, TIMESTAMPTZ '2026-11-27 01:00:00+00') <> DATE '2026-11-26' THEN
      RAISE EXCEPTION 'FAIL 5i: branch business date'; END IF;
  END IF;
  -- Period keys: FY = FY + start year (same as doc-seq 0670); WEEK from the tenant week start (Sunday here).
  IF public.fn_cmx_dt_period_key(v_a, 'invoice', NULL, 'FY', TIMESTAMPTZ '2027-02-10 08:00:00+00') <> 'FY2026'
     OR public.fn_cmx_dt_period_key(v_a, 'invoice', NULL, 'FY', TIMESTAMPTZ '2027-04-01 08:00:00+00') <> 'FY2027' THEN
    RAISE EXCEPTION 'FAIL 5j: FY key'; END IF;
  IF public.fn_cmx_dt_period_key(v_a, 'invoice', NULL, 'WEEK', TIMESTAMPTZ '2026-11-26 08:00:00+00') <> 'W20261122' THEN
    RAISE EXCEPTION 'FAIL 5k: WEEK key (Sunday start) gave %', public.fn_cmx_dt_period_key(v_a, 'invoice', NULL, 'WEEK', TIMESTAMPTZ '2026-11-26 08:00:00+00'); END IF;
  UPDATE public.org_tenants_mst SET first_day_of_week = 6 WHERE id = v_a;
  IF public.fn_cmx_dt_period_key(v_a, 'invoice', NULL, 'WEEK', TIMESTAMPTZ '2026-11-26 08:00:00+00') <> 'W20261121' THEN
    RAISE EXCEPTION 'FAIL 5l: WEEK key (Saturday start)'; END IF;
  IF public.fn_cmx_dt_period_key(v_a, 'invoice', NULL, 'DAY', TIMESTAMPTZ '2026-11-26 21:00:00+00') <> '20261127' THEN
    RAISE EXCEPTION 'FAIL 5m: DAY key'; END IF;
  -- Same FY rule as the doc-seq engine (0670) when it is installed.
  IF to_regprocedure('public.fn_doc_seq_period_key(text, timestamptz, text, smallint)') IS NOT NULL THEN
    EXECUTE $q$SELECT public.fn_doc_seq_period_key('FISCAL_YEAR', TIMESTAMPTZ '2027-02-10 08:00:00+00', 'Asia/Muscat', 4::smallint)$q$ INTO v_cc;
    IF v_cc <> 'FY2026' THEN RAISE EXCEPTION 'FAIL 5n: doc-seq FY key % differs', v_cc; END IF;
  END IF;
  -- Platform step when the country has no default.
  UPDATE public.org_tenants_mst SET time_format = NULL, first_day_of_week = NULL, country = 'ZZ' WHERE id = v_a;
  SELECT * INTO s FROM public.fn_cmx_dt_settings(v_a);
  IF s.hour_cycle_source <> 'platform' OR s.week_start_source <> 'platform' THEN RAISE EXCEPTION 'FAIL 5o: platform fallback'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.fn_cmx_dt_chk_country_unknown(v_a)) OR NOT EXISTS (SELECT 1 FROM public.fn_cmx_dt_chk_setting_unresolved(v_a)) THEN
    RAISE EXCEPTION 'FAIL 5p: CLOCK_COUNTRY_UNKNOWN / CLOCK_SETTING_UNRESOLVED not reported'; END IF;
  UPDATE public.org_tenants_mst SET country = 'OM' WHERE id = v_a;
  RAISE NOTICE 'PASS 5: settings tenant/country/platform, business date and bounds, cut-over range, FY and WEEK keys, health';
END $$;

-- ------------------------------------------------------------------
-- 6. Grants (§7.16) and tenant isolation
-- ------------------------------------------------------------------
DO $$
DECLARE
  v_a UUID := (SELECT v::uuid FROM zz_ctx WHERE k = 'a');
  v_b UUID := (SELECT v::uuid FROM zz_ctx WHERE k = 'b');
  v_fn TEXT; v_bad TEXT;
BEGIN
  -- anon: only the clock functions.
  SELECT string_agg(p.oid::regprocedure::text, ', ') INTO v_bad
    FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
   WHERE n.nspname = 'public' AND (p.proname LIKE 'fn\_cmx\_dt\_%' OR p.proname LIKE 'fn\_shc\_clock\_%')
     AND p.proname !~ '^fn_cmx_dt_(now|clock|_fake_(instant|now|clock))$'
     AND has_function_privilege('anon', p.oid, 'EXECUTE');
  IF v_bad IS NOT NULL THEN RAISE EXCEPTION 'FAIL 6a: anon may execute %', v_bad; END IF;
  IF NOT has_function_privilege('anon', 'public.fn_cmx_dt_now()', 'EXECUTE') THEN RAISE EXCEPTION 'FAIL 6b: anon needs fn_cmx_dt_now (column defaults)'; END IF;
  IF has_function_privilege('authenticated', 'public.fn_cmx_dt_health(uuid)', 'EXECUTE') THEN RAISE EXCEPTION 'FAIL 6c: authenticated may run fn_cmx_dt_health'; END IF;
  IF has_table_privilege('authenticated', 'public.cmx_dt_env_cf', 'SELECT') OR has_table_privilege('service_role', 'public.cmx_dt_env_cf', 'UPDATE')
     OR has_table_privilege('anon', 'public.cmx_dt_env_cf', 'SELECT') THEN
    RAISE EXCEPTION 'FAIL 6d: cmx_dt_env_cf must be owner-only'; END IF;
  -- Every new function pins search_path.
  SELECT string_agg(p.proname, ', ') INTO v_bad
    FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
   WHERE n.nspname = 'public' AND p.proname LIKE 'fn\_cmx\_dt\_%' AND p.prolang <> (SELECT oid FROM pg_language WHERE lanname = 'sql')
     AND NOT EXISTS (SELECT 1 FROM unnest(p.proconfig) c WHERE c LIKE 'search\_path=%');
  IF v_bad IS NOT NULL THEN RAISE EXCEPTION 'FAIL 6e: no search_path on %', v_bad; END IF;
  -- A signed-in user of tenant A cannot read tenant B.
  PERFORM set_config('request.jwt.claims', json_build_object('sub', '00000000-0000-0000-0000-0000000000aa', 'role', 'authenticated', 'tenant_org_id', v_a)::text, true);
  SET LOCAL ROLE authenticated;
  BEGIN
    PERFORM public.fn_cmx_dt_settings(v_b);
    RESET ROLE; RAISE EXCEPTION 'FAIL 6f: cross-tenant settings read';
  EXCEPTION WHEN insufficient_privilege THEN NULL;
  END;
  BEGIN
    PERFORM public.fn_cmx_dt_zone(v_b, 'accept_order', NULL);
    RESET ROLE; RAISE EXCEPTION 'FAIL 6g: cross-tenant zone read';
  EXCEPTION WHEN insufficient_privilege THEN NULL;
  END;
  BEGIN
    PERFORM public.fn_cmx_dt_chk_zone_missing(NULL);
    RESET ROLE; RAISE EXCEPTION 'FAIL 6h: all-tenant health as authenticated';
  EXCEPTION WHEN insufficient_privilege THEN NULL;
  END;
  IF public.fn_cmx_dt_hour_cycle(v_a) IS NULL OR public.fn_cmx_dt_zone(v_a, 'accept_order', NULL) <> 'Asia/Muscat' THEN
    RESET ROLE; RAISE EXCEPTION 'FAIL 6i: own tenant read as authenticated'; END IF;
  RESET ROLE;
  PERFORM set_config('request.jwt.claims', '', true);
  RAISE NOTICE 'PASS 6: anon only gets the clock, health is service-only, env table owner-only, search_path pinned, tenant isolation';
END $$;

-- ------------------------------------------------------------------
-- 7. Setup health (0709 contract) and the clock health aggregator
-- ------------------------------------------------------------------
DO $$
DECLARE
  v_a UUID := (SELECT v::uuid FROM zz_ctx WHERE k = 'a');
  v_n INTEGER; v_bad TEXT;
BEGIN
  SELECT count(*), string_agg(r.check_code || '=' || r.status, ', ') FILTER (WHERE r.status NOT IN ('OK', 'FAIL', 'NA'))
    INTO v_n, v_bad FROM public.fn_setup_health_run(v_a, NULL, 'CLOCK') r;
  IF v_bad IS NOT NULL THEN RAISE EXCEPTION 'FAIL 7a: CLOCK checks returned %', v_bad; END IF;
  IF v_n <> (SELECT count(*) FROM public.sys_setup_health_check_cd WHERE domain_code = 'CLOCK' AND is_active AND rec_status = 1) THEN
    RAISE EXCEPTION 'FAIL 7b: one row per CLOCK check expected'; END IF;
  IF (SELECT count(*) FROM public.sys_setup_health_check_cd WHERE domain_code = 'CLOCK') < 11 THEN RAISE EXCEPTION 'FAIL 7c: 11 CLOCK checks expected'; END IF;
  IF EXISTS (SELECT 1 FROM public.sys_setup_health_check_cd WHERE domain_code = 'CLOCK' AND shows_banner AND check_code NOT IN ('CLOCK_ZONE_MISSING', 'CLOCK_ZONE_INVALID')) THEN
    RAISE EXCEPTION 'FAIL 7d: banner only for zone missing / invalid'; END IF;
  IF (SELECT r.status FROM public.fn_setup_health_run(v_a, NULL, 'CLOCK', ARRAY['CLOCK_ZONE_MISSING']) r) <> 'OK' THEN
    RAISE EXCEPTION 'FAIL 7e: tenant A has a zone'; END IF;
  UPDATE public.org_tenants_mst SET timezone = NULL WHERE id = v_a;
  IF (SELECT r.status FROM public.fn_setup_health_run(v_a, NULL, 'CLOCK', ARRAY['CLOCK_ZONE_MISSING']) r) <> 'FAIL' THEN
    RAISE EXCEPTION 'FAIL 7f: CLOCK_ZONE_MISSING must FAIL'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.fn_cmx_dt_health(NULL) h WHERE h.check_code = 'CLOCK_ZONE_MISSING' AND h.tenant_org_id = v_a) THEN
    RAISE EXCEPTION 'FAIL 7g: aggregator misses CLOCK_ZONE_MISSING'; END IF;
  IF EXISTS (SELECT 1 FROM public.fn_cmx_dt_health(NULL) h WHERE h.detail ->> 'status' = 'ERROR') THEN
    RAISE EXCEPTION 'FAIL 7h: a clock check failed: %', (SELECT string_agg(h.check_code || ' ' || (h.detail ->> 'message'), '; ') FROM public.fn_cmx_dt_health(NULL) h WHERE h.detail ->> 'status' = 'ERROR'); END IF;
  UPDATE public.org_tenants_mst SET timezone = 'Asia/Muscat' WHERE id = v_a;
  IF EXISTS (SELECT 1 FROM public.fn_cmx_dt_chk_role_tz_utc(NULL)) THEN
    RAISE NOTICE 'NOTE 7: CLOCK_ROLE_TZ_UTC findings (Q1): %', (SELECT string_agg(h.detail::text, '; ') FROM public.fn_cmx_dt_chk_role_tz_utc(NULL) h);
  END IF;
  RAISE NOTICE 'PASS 7: setup-health CLOCK domain, banner rule, aggregator';
END $$;

ROLLBACK;
